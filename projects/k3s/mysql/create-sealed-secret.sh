#!/bin/bash
# Generates sealed-secret.yaml (Secret mysql-credentials) from secrets.env.
# Without secrets.env a random root password is generated.

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SECRETS_FILE="${SCRIPT_DIR}/secrets.env"
OUTPUT_FILE="${SCRIPT_DIR}/sealed-secret.yaml"
NAMESPACE="mysql"
SECRET_NAME="mysql-credentials"
KUBECONFIG_PATH="/etc/rancher/k3s/k3s.yaml"

KUBESEAL_BIN="${KUBESEAL_BIN:-$(command -v kubeseal || echo "${HOME}/.local/bin/kubeseal")}"
if [ ! -x "${KUBESEAL_BIN}" ]; then
    echo "ERROR: kubeseal is not installed. Run ../sealed-secrets/setup.sh first."
    exit 1
fi

# User-profile copy of the generated secrets, for the user to read and back up.
SECRETS_COPY_DIR="${HOME}/.config/gucef-k3s"
SECRETS_COPY="${SECRETS_COPY_DIR}/mysql-secrets.env"

random_password()
{
    openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c 32
}

if [ ! -f "${SECRETS_FILE}" ]; then
    echo "${SECRETS_FILE} not found - generating a random root password..."
    umask 077
    {
        echo "# Generated by create-sealed-secret.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo "# Gitignored. A copy is kept in ${SECRETS_COPY}"
        echo "MYSQL_ROOT_PASSWORD=$(random_password)"
    } > "${SECRETS_FILE}"
fi

mkdir -p "${SECRETS_COPY_DIR}" && chmod 700 "${SECRETS_COPY_DIR}"
cp "${SECRETS_FILE}" "${SECRETS_COPY}"
chmod 600 "${SECRETS_COPY}"
echo "Credentials copy: ${SECRETS_COPY}"

# Strip Windows carriage returns in case the file was edited on Windows
set -a
source <(sed 's/\r//' "${SECRETS_FILE}")
set +a

if [ -z "${MYSQL_ROOT_PASSWORD}" ]; then
    echo "ERROR: MYSQL_ROOT_PASSWORD must be set in secrets.env"
    exit 1
fi

echo "Generating sealed secret for namespace: ${NAMESPACE}..."
kubectl create secret generic "${SECRET_NAME}" \
    --namespace "${NAMESPACE}" \
    --from-literal=MYSQL_ROOT_PASSWORD="${MYSQL_ROOT_PASSWORD}" \
    --dry-run=client -o yaml \
| "${KUBESEAL_BIN}" \
    --kubeconfig "${KUBECONFIG_PATH}" \
    --controller-name=sealed-secrets \
    --controller-namespace=kube-system \
    --format yaml \
> "${OUTPUT_FILE}"

echo "Sealed secret written to ${OUTPUT_FILE}"
