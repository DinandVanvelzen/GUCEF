#!/bin/bash

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
SECRETS_FILE="${SCRIPT_DIR}/secrets.env"
CONFIG_FILE="${SCRIPT_DIR}/config.env"
OUTPUT_FILE="${SCRIPT_DIR}/sealed-secret.yaml"
NAMESPACE="forgejo"
SECRET_NAME="forgejo-credentials"
KUBECONFIG_PATH="/etc/rancher/k3s/k3s.yaml"

KUBESEAL_BIN="${KUBESEAL_BIN:-$(command -v kubeseal || echo "${HOME}/.local/bin/kubeseal")}"
if [ ! -x "${KUBESEAL_BIN}" ]; then
    echo "ERROR: kubeseal is not installed. Run ../sealed-secrets/setup.sh first."
    exit 1
fi

# User-profile copy of the generated secrets, for the user to read and back up.
SECRETS_COPY_DIR="${HOME}/.config/gucef-k3s"
SECRETS_COPY="${SECRETS_COPY_DIR}/forgejo-secrets.env"

random_password()
{
    openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c 32
}

# Without secrets.env, random passwords are generated (alphanumeric, 32 characters).
if [ ! -f "${SECRETS_FILE}" ]; then
    echo "${SECRETS_FILE} not found - generating random credentials..."
    umask 077
    {
        echo "# Generated by create-sealed-secret.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)"
        echo "# Gitignored. A copy is kept in ${SECRETS_COPY}"
        echo "FORGEJO_DB_PASSWORD=$(random_password)"
        echo "FORGEJO_ADMIN_PASSWORD=$(random_password)"
        echo "GITHUB_TOKEN="
    } > "${SECRETS_FILE}"
fi

# Keep the copy in the user profile in sync with secrets.env (plus the login user name)
[ -f "${CONFIG_FILE}" ] && FORGEJO_ADMIN_USER=$(sed 's/\r//' "${CONFIG_FILE}" | grep -E '^FORGEJO_ADMIN_USER=' | tail -n 1 | cut -d= -f2-)
FORGEJO_ADMIN_USER="${FORGEJO_ADMIN_USER:-forgejo-admin}"
mkdir -p "${SECRETS_COPY_DIR}" && chmod 700 "${SECRETS_COPY_DIR}"
{
    echo "# Forgejo web login: user name below, password FORGEJO_ADMIN_PASSWORD."
    echo "FORGEJO_ADMIN_USER=${FORGEJO_ADMIN_USER}"
    cat "${SECRETS_FILE}"
} > "${SECRETS_COPY}"
chmod 600 "${SECRETS_COPY}"
echo "Credentials copy: ${SECRETS_COPY}"

# Load config (optional) and secrets (strip Windows carriage returns in case file was edited on Windows)
set -a
if [ -f "${CONFIG_FILE}" ]; then
    source <(sed 's/\r//' "${CONFIG_FILE}")
fi
source <(sed 's/\r//' "${SECRETS_FILE}")
set +a

FORGEJO_ADMIN_USER="${FORGEJO_ADMIN_USER:-forgejo-admin}"

if [ -z "${FORGEJO_DB_PASSWORD}" ] || [ -z "${FORGEJO_ADMIN_PASSWORD}" ]; then
    echo "ERROR: FORGEJO_DB_PASSWORD and FORGEJO_ADMIN_PASSWORD must both be set in secrets.env"
    exit 1
fi

echo "Generating sealed secret for namespace: ${NAMESPACE}..."

# Keys: DB_PASSWORD (database), username + password (chart admin secret format),
# GITHUB_TOKEN (optional, may be empty).
kubectl create secret generic "${SECRET_NAME}" \
    --namespace "${NAMESPACE}" \
    --from-literal=DB_PASSWORD="${FORGEJO_DB_PASSWORD}" \
    --from-literal=username="${FORGEJO_ADMIN_USER}" \
    --from-literal=password="${FORGEJO_ADMIN_PASSWORD}" \
    --from-literal=GITHUB_TOKEN="${GITHUB_TOKEN}" \
    --dry-run=client -o yaml \
| "${KUBESEAL_BIN}" \
    --kubeconfig "${KUBECONFIG_PATH}" \
    --controller-name=sealed-secrets \
    --controller-namespace=kube-system \
    --format yaml \
> "${OUTPUT_FILE}"

echo "Sealed secret written to ${OUTPUT_FILE}"
echo "This file is safe to commit to git."
