#!/bin/bash
# ---------------------------------------------------------------------------
# Keeps secrets.env complete and sealed-secret.yaml (Secret irc-credentials) in step with it.
#
# - Missing values in secrets.env are generated: passwords, the API token, a password per
#   account in IRC_ADMIN_ACCOUNT / IRC_ACCOUNTS, and the bcrypt hashes of the operator
#   passwords (made by "ergo genpasswd" in a short-lived pod). Account passwords are three
#   words and a number (irc_easy_password); the others are 32 random characters.
# - secrets.env is copied to ~/.config/gucef-k3s/irc-secrets.env.
# - sealed-secret.yaml is regenerated when it is missing or older than secrets.env.
#
# Account passwords stay in secrets.env only; the cluster Secret holds what the server needs.
# The bot passwords and vendor API keys go to the Secret irc-hub-secrets, which setup.sh makes.
# ---------------------------------------------------------------------------

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
source "${SCRIPT_DIR}/lib.sh"
irc_load_config

SECRETS_FILE="${SCRIPT_DIR}/secrets.env"
OUTPUT_FILE="${SCRIPT_DIR}/sealed-secret.yaml"
SECRETS_COPY_DIR="${HOME}/.config/gucef-k3s"
SECRETS_COPY="${SECRETS_COPY_DIR}/irc-secrets.env"

KUBESEAL_BIN="${KUBESEAL_BIN:-$(irc_find_kubeseal)}"
[ -x "${KUBESEAL_BIN}" ] || irc_fail "kubeseal is not installed." "Run ../sealed-secrets/setup.sh first."

random_password()
{
    openssl rand -base64 64 | tr -dc 'A-Za-z0-9' | head -c 32
}

SECRETS_CHANGED=false
add_secret()
{
    echo "$1=$2" >> "${SECRETS_FILE}"
    SECRETS_CHANGED=true
}

umask 077
if [ ! -f "${SECRETS_FILE}" ]; then
    echo "# Generated by create-sealed-secret.sh. Gitignored. A copy is kept in ${SECRETS_COPY}" > "${SECRETS_FILE}"
    SECRETS_CHANGED=true
fi

for KEY in IRC_DB_PASSWORD IRC_API_TOKEN IRC_STEWARD_PASSWORD IRC_ADMIN_OPER_PASSWORD IRC_BOT_OPER_PASSWORD; do
    [ -n "$(irc_local_secret ${KEY})" ] || add_secret "${KEY}" "$(random_password)"
done
for ACCT in ${IRC_ALL_ACCOUNTS}; do
    [ -n "$(irc_local_secret "IRC_PASSWORD_${ACCT}")" ] || { echo "Generating a password for account ${ACCT}"; add_secret "IRC_PASSWORD_${ACCT}" "$(irc_easy_password)"; }
done

for BOT in ${IRC_BOTS}; do
    [ -n "$(irc_local_secret "IRC_BOT_PASSWORD_${BOT}")" ] || add_secret "IRC_BOT_PASSWORD_${BOT}" "$(random_password)"
done
# The API keys of the vendors: empty until you fill them in; a bot runs once its key has a value
for BOT in ${IRC_BOTS}; do
    KEY=$(irc_bot_setting "${BOT}" API_KEY)
    [ -z "${KEY}" ] || grep -q "^${KEY}=" "${SECRETS_FILE}" || add_secret "${KEY}" ""
done

# bcrypt hash of a password, by the Ergo binary of the configured image
ergo_genpasswd()
{
    ${KC} create namespace ${NAMESPACE} --dry-run=client -o yaml | ${KC} apply -f - >/dev/null
    printf '%s\n' "$1" | ${KC} -n ${NAMESPACE} run "ergo-genpasswd-$$-${RANDOM}" --rm -i --quiet --restart=Never \
        --image="${IRC_ERGO_IMAGE}" --command -- /ircd-bin/ergo genpasswd 2>/dev/null \
        | grep -o '\$2[aby]\$[0-9][0-9]\$[./A-Za-z0-9]\{53\}' | head -n 1
}

for PAIR in IRC_ADMIN_OPER_HASH:IRC_ADMIN_OPER_PASSWORD IRC_STEWARD_OPER_HASH:IRC_STEWARD_PASSWORD IRC_BOT_OPER_HASH:IRC_BOT_OPER_PASSWORD; do
    HASH_KEY="${PAIR%%:*}"
    PASS_KEY="${PAIR##*:}"
    if [ -z "$(irc_local_secret ${HASH_KEY})" ]; then
        echo "Hashing ${PASS_KEY} with ergo genpasswd..."
        HASH=$(ergo_genpasswd "$(irc_local_secret ${PASS_KEY})")
        [ -n "${HASH}" ] || irc_fail "ergo genpasswd did not return a hash." "Can the cluster pull ${IRC_ERGO_IMAGE}?"
        add_secret "${HASH_KEY}" "${HASH}"
    fi
done

mkdir -p "${SECRETS_COPY_DIR}" && chmod 700 "${SECRETS_COPY_DIR}"
{
    echo "# IRC server credentials. Log in with SASL PLAIN: account name + IRC_PASSWORD_<account>."
    echo "# Administrator account: ${IRC_ADMIN_ACCOUNT}; operator: /OPER admin <IRC_ADMIN_OPER_PASSWORD>"
    cat "${SECRETS_FILE}"
} > "${SECRETS_COPY}"
chmod 600 "${SECRETS_COPY}"

if [ "${SECRETS_CHANGED}" != "true" ] && [ -f "${OUTPUT_FILE}" ] && [ "${OUTPUT_FILE}" -nt "${SECRETS_FILE}" ]; then
    echo "sealed-secret.yaml is up to date."
    exit 0
fi

echo "Generating sealed secret for namespace: ${NAMESPACE}..."
${KC} create secret generic irc-credentials \
    --namespace "${NAMESPACE}" \
    --from-literal=DB_PASSWORD="$(irc_local_secret IRC_DB_PASSWORD)" \
    --from-literal=API_TOKEN="$(irc_local_secret IRC_API_TOKEN)" \
    --from-literal=STEWARD_PASSWORD="$(irc_local_secret IRC_STEWARD_PASSWORD)" \
    --from-literal=ADMIN_OPER_HASH="$(irc_local_secret IRC_ADMIN_OPER_HASH)" \
    --from-literal=STEWARD_OPER_HASH="$(irc_local_secret IRC_STEWARD_OPER_HASH)" \
    --from-literal=BOT_OPER_HASH="$(irc_local_secret IRC_BOT_OPER_HASH)" \
    --dry-run=client -o yaml \
| "${KUBESEAL_BIN}" \
    --kubeconfig "${KUBECONFIG_PATH}" \
    --controller-name=sealed-secrets \
    --controller-namespace=kube-system \
    --format yaml \
> "${OUTPUT_FILE}.tmp" || { rm -f "${OUTPUT_FILE}.tmp"; irc_fail "kubeseal failed."; }
mv "${OUTPUT_FILE}.tmp" "${OUTPUT_FILE}"
echo "Sealed secret written to ${OUTPUT_FILE}"
