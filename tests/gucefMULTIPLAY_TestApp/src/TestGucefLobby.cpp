/** Something the test waits for */
class CCondition
{
    public:
    virtual ~CCondition() {}
    virtual bool IsMet( void ) = 0;
};

/*-------------------------------------------------------------------------*/

static bool
PumpUntil( CCondition& condition, UInt32 timeoutInMs )
{
    UInt64 deadline = CORE::CSystemMonotonicClock::Instance().GetMonotonicTimeInMs() + timeoutInMs;
    while ( CORE::CSystemMonotonicClock::Instance().GetMonotonicTimeInMs() < deadline )
    {
        if ( condition.IsMet() )
            return true;
        CORE::CCoreGlobal::Instance()->GetPulseGenerator()->ForceDirectPulse();
        MT::ThreadDelay( 1 );
    }
    return condition.IsMet();
}

