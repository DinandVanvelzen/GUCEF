/** A lobby server and clients on loopback: alice (boss), bob and carol (players), dave (a spectator) */
class CGucefFixture
{
    public:

    MULTIPLAY::CGucefLobbyServerSettings serverSettings;
    MULTIPLAY::CGucefLobbyServer server;
    MULTIPLAY::CLobbyCreateParams params;
    MULTIPLAY::CILobbyServicePtr services[ 5 ];
    MULTIPLAY::CILobbyPtr lobbies[ 5 ];
    CLobbyRecorder events[ 5 ];
    CORE::CString channelType;
    CORE::CString lobbyId;
    UInt16 serverPort;
    UInt16 gamePorts[ 5 ];

    explicit CGucefFixture( const CORE::CString& channel = "tcp" )
        : serverSettings(), server(), params(), channelType( channel ), lobbyId(), serverPort( NextPort() )
    {
        for ( UInt32 i=0; i<5; ++i )
            gamePorts[ i ] = NextPort();

        serverSettings.node.listenEndpoints.FromString( channelType + "://127.0.0.1:" + CORE::ToString( serverPort ) );
        serverSettings.relayListen.FromString( channelType + "://127.0.0.1:" + CORE::ToString( NextPort() ) );   // used when a test enables the relay
        serverSettings.node.echoIntervalMs = 50;
        serverSettings.node.pulseIntervalMs = 1;
        serverSettings.secondInMs = 50;
        serverSettings.latencyIntervalInMs = 100;
        serverSettings.rules.minPlayers = 2;
        serverSettings.rules.countdownInSecs = 3;
        serverSettings.rules.voteDurationInSecs = 1;
        serverSettings.rules.requireAllReady = true;
        serverSettings.rules.allowForceStart = true;
        serverSettings.rules.startByVote = true;
        serverSettings.rules.closeWhenHostLeaves = false;

        params.name = "Gucef lobby";
        params.gameId = "testgame";
        params.gameVersion = "1.0";
        params.maxPlayers = 4;
        params.allowSpectators = true;
        params.isPublic = true;
        params.topology = MULTIPLAY::GAMETOPOLOGY_CLIENT_SERVER;

        MULTIPLAY::CLobbySettingDef map;
        map.key = "map";
        map.type = MULTIPLAY::CLobbySettingDef::TYPE_ENUM;
        map.options.push_back( "dust" );
        map.options.push_back( "ice" );
        map.defaultValue = "dust";
        params.schema.AddSetting( map );
        MULTIPLAY::CLobbySettingDef speed;
        speed.key = "speed";
        speed.type = MULTIPLAY::CLobbySettingDef::TYPE_INT;
        speed.hasRange = true;
        speed.minValue = 1;
        speed.maxValue = 5;
        speed.defaultValue = "3";
        speed.changePolicy = MULTIPLAY::CLobbySettingDef::CHANGEPOLICY_VOTE;
        params.schema.AddSetting( speed );
        MULTIPLAY::CLobbySettingDef handicap;
        handicap.key = "handicap";
        handicap.type = MULTIPLAY::CLobbySettingDef::TYPE_INT;
        handicap.hasRange = true;
        handicap.minValue = 0;
        handicap.maxValue = 100;
        handicap.defaultValue = "0";
        handicap.changePolicy = MULTIPLAY::CLobbySettingDef::CHANGEPOLICY_OWNER;
        params.schema.AddSetting( handicap );
        params.schema.factions.push_back( "arm" );
        params.schema.factions.push_back( "core" );
        params.schema.colours.push_back( "red" );
        params.schema.colours.push_back( "blue" );
        params.schema.colours.push_back( "green" );
        params.schema.uniqueColours = true;
    }

    ~CGucefFixture()
    {
        for ( UInt32 i=0; i<5; ++i )
            lobbies[ i ] = MULTIPLAY::CILobbyPtr();
        PumpFor( 20 );
        for ( UInt32 i=0; i<5; ++i )
            services[ i ] = MULTIPLAY::CILobbyServicePtr();
        PumpFor( 20 );
        server.Stop();
    }

    MULTIPLAY::CGucefLobbyService& Service( UInt32 index )
    {
        return *static_cast< MULTIPLAY::CGucefLobbyService* >( services[ index ].GetPointerAlways() );
    }

    MULTIPLAY::CGucefLobby& Lobby( UInt32 index )
    {
        return *static_cast< MULTIPLAY::CGucefLobby* >( lobbies[ index ].GetPointerAlways() );
    }

    CORE::CString GameEndpoint( UInt32 index ) const
    {
        return channelType + "://127.0.0.1:" + CORE::ToString( gamePorts[ index ] );
    }

    bool StartServer( void )
    {
        server.SetSettings( serverSettings );
        return server.Start();
    }

    bool Connect( UInt32 index, const CORE::CString& password = CORE::CString::Empty )
    {
        return ConnectAs( index, Identities[ index ], password, server.GetEndpoints() );
    }

    bool ConnectAs( UInt32 index, const MULTIPLAY::CPlayerIdentity& identity, const CORE::CString& password, const DRN::CDRNEndpointList& serverEndpoints,
                    MULTIPLAY::CIClientIntegrity* integrity = GUCEF_NULL )
    {
        services[ index ] = MULTIPLAY::CMultiplayGlobal::Instance()->GetLobbyServiceFactory().Create( "gucef" );
        if ( services[ index ].IsNULL() )
            return false;
        MULTIPLAY::CGucefLobbyService& service = Service( index );
        service.SetServerEndpoints( serverEndpoints );
        service.SetPassword( password );
        service.SetClientIntegrity( integrity );
        CORE::CString::StringVector endpoints;
        endpoints.push_back( GameEndpoint( index ) );
        service.SetLocalEndpoints( endpoints );

        CORE::CFutureResult future( CORE::TTaskStatus::TASKSTATUS_UNDEFINED );
        if ( !service.Connect( identity, future ) )
            return false;
        CFutureReady ready( future );
        return PumpUntil( ready, 10000 ) && service.IsConnected();
    }

    bool Enter( UInt32 index, bool create, bool asSpectator )
    {
        CORE::CFutureResult future( CORE::TTaskStatus::TASKSTATUS_UNDEFINED );
        bool sent = create ? services[ index ]->CreateLobby( params, future ) : services[ index ]->JoinLobby( lobbyId, params.password, asSpectator, future );
        if ( !sent )
            return false;
        CFutureReady ready( future );
        if ( !PumpUntil( ready, 10000 ) || !MULTIPLAY::CILobbyService::TryGetLobbyFromFuture( future, lobbies[ index ] ) )
            return false;
        events[ index ].Watch( lobbies[ index ] );
        if ( create )
            lobbyId = lobbies[ index ]->GetState().lobbyId;
        return true;
    }

    bool Setup( UInt32 memberCount = 4 )
    {
        if ( !StartServer() )
            return false;
        for ( UInt32 i=0; i<memberCount; ++i )
            if ( !Connect( i ) )
                return false;
        if ( !Enter( 0, true, false ) )
            return false;
        for ( UInt32 i=1; i<memberCount; ++i )
            if ( !Enter( i, false, 3 == i ) )
                return false;
        for ( UInt32 i=0; i<memberCount; ++i )
        {
            CStateCondition everyone( lobbies[ i ], CStateCondition::MEMBER_COUNT, CORE::CString::Empty, CORE::CString::Empty, (Int32) memberCount );
            if ( !PumpUntil( everyone, 10000 ) )
                return false;
        }
        return true;
    }

    /** Waits until every lobby has the setting */
    bool WaitForSetting( const CORE::CString& key, const CORE::CString& value, UInt32 count = 4 )
    {
        for ( UInt32 i=0; i<count; ++i )
        {
            if ( lobbies[ i ].IsNULL() )
                continue;
            CStateCondition condition( lobbies[ i ], CStateCondition::SETTING, key, value );
            if ( !PumpUntil( condition, 5000 ) )
                return false;
        }
        return true;
    }
};

