    typedef typename TForm::TAbstractFactory TAbstractFactory;

    typename TForm::template TConcrete< 1 >::Type first;
    typename TForm::template TConcrete< 2 >::Type second;
    typename TForm::template TConcrete< 3 >::Type sharedA;
    typename TForm::template TConcrete< 3 >::Type sharedB;
    const CString firstName = first.GetConcreteClassTypeName();
    const CString secondName = second.GetConcreteClassTypeName();
    const CString sharedName = sharedA.GetConcreteClassTypeName();
    TAbstractFactory factory( false );

    factory.RegisterConcreteFactory( "X", &first );
    factory.RegisterConcreteFactory( "X", &second );     // replaces the first
    GUCEF_TESTFW_ASSERT_FALSE( factory.IsClassConstructible( firstName ) );
    GUCEF_TESTFW_ASSERT_TRUE( factory.IsClassConstructible( secondName ) );
    GUCEF_TESTFW_ASSERT_TRUE( TForm::CreateByClass( factory, firstName ).IsNULL() );
