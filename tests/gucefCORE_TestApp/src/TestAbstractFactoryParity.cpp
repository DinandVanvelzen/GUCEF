    GUCEF_TESTFW_ASSERT_TRUE( factory.IsClassConstructible( sharedName ) );
    factory.UnregisterConcreteFactory( "A" );
    GUCEF_TESTFW_ASSERT_FALSE( factory.IsClassConstructible( sharedName ) );
