bool
CWebJson::ToText( const CORE::CDataNode& tree, CORE::CString& jsonText )
{GUCEF_TRACE;

    CORE::CDStoreCodecRegistry::TDStoreCodecPtr codec;
    if ( !CORE::CCoreGlobal::Instance()->GetDStoreCodecRegistry().TryLookup( "json", codec, false ) || codec.IsNULL() )
        return false;
    CORE::CDynamicBuffer buffer;
    CORE::CDynamicBufferAccess access( buffer );
    if ( !codec->StoreDataTree( &tree, &access ) )
        return false;
    jsonText.Set( buffer.AsConstTypePtr< char >(), buffer.GetDataSize() );
    return true;
}

/*-------------------------------------------------------------------------*/

bool
CWebJson::FromText( const CORE::CString& jsonText, CORE::CDataNode& tree )
{GUCEF_TRACE;

    CORE::CDStoreCodecRegistry::TDStoreCodecPtr codec;
    if ( !CORE::CCoreGlobal::Instance()->GetDStoreCodecRegistry().TryLookup( "json", codec, false ) || codec.IsNULL() )
        return false;
    CORE::CDynamicBuffer buffer;
    buffer.CopyFrom( jsonText, 0, false );
    CORE::CDynamicBufferAccess access( buffer );
    return codec->BuildDataTree( &tree, &access );
}

