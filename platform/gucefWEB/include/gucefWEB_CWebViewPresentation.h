/**
 *  How a presenter shows a view: the title of its window, the prompt above the page, modality and which chrome the
 *  form shows. Nothing in it is secret.
 */
class GUCEF_WEB_PUBLIC_CPP CWebViewPresentation
{
    public:

    CString title;
    CString prompt;                 /**< the banner above the page: "Sign in to ...", "Solve the puzzle to continue" */
    bool modal;
    bool showNavigationBar;         /**< back, forward, reload and the address */
    bool addressEditable;           /**< the person may type an address (never in sign-in use) */
    bool showStatusBar;
    bool showDialogButtons;         /**< Cancel */
    bool cancelAllowed;

    CWebViewPresentation( void );
};

