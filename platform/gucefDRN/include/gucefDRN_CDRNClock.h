{
    public:

    /** Monotonic microseconds since a process wide origin */
    static UInt64 NowInMicroseconds( void );

    /** Monotonic milliseconds since the same origin */
    static UInt64 NowInMilliseconds( void );

    private:

    CDRNClock( void );
};

