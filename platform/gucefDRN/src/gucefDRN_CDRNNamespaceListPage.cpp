CDRNNamespaceListPage::CDRNNamespaceListPage( void )
    : entries()
    , nextCursor()
    , dirRevision()
    , unchanged( false )
{GUCEF_TRACE;

}

/*-------------------------------------------------------------------------*/

void
CDRNNamespaceListPage::Clear( void )
{GUCEF_TRACE;

    entries.clear();
    nextCursor.Clear();
    dirRevision.Clear();
    unchanged = false;
}

/*-------------------------------------------------------------------------*/

bool
CDRNNamespaceListPage::IsLast( void ) const
{GUCEF_TRACE;

    return nextCursor.IsNULLOrEmpty();
}

