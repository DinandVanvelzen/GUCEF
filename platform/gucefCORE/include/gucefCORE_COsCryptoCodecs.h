/**
 *  The crypto facilities of the operating system as codecs: AF_ALG on Linux, CNG on Windows, CommonCrypto on macOS.
 *  Each platform has its own implementation (src/linux, src/mswin, src/osx); platforms without one offer none.
 */
class GUCEF_CORE_PUBLIC_CPP COsCryptoCodecs
{
    public:

    /** Probes what the OS offers and adds a codec per available algorithm, absent algorithms are left out */
    static void CreateCodecs( CCodecRegistry::TICodecPtrVector& codecs );

    /** The name of the OS facility, empty when the platform has none */
    static const char* GetProviderName( void );
};

