/**
 *  A named control action that the generic model does not know, declared by a work source or the service
 *  (JOBCONTROLACTION_CUSTOM): for example the investment "watchlist-add". Arguments are name = text pairs.
 */
struct GUCEF_CORE_PUBLIC_CPP SJobCustomAction
{
    CString name;
    CString title;
    TJobControlTargetKind targetKind;
    CString::StringVector argumentNames;
    bool privileged;                    /**< needs the per action role refinement of the remote layer */

    SJobCustomAction( void );
};

