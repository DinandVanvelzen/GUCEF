const CString&
ServiceHealthStateToString( TServiceHealthState state )
{GUCEF_TRACE;

    static const CString pass( "pass" );
    static const CString warn( "warn" );
    static const CString fail( "fail" );
    switch ( state )
    {
        case HEALTH_PASS: return pass;
        case HEALTH_WARN: return warn;
        default: return fail;
    }
}

