/**
 *  Module-private: one TaskManager/Watch call: what it wants, how often, and the latest sample message that could not
 *  be written for lack of credit (latest wins, samples are never queued). Notification thread only.
 */
class CTaskManagerWatchStream
{
    public:

    COMCORE::CRpcServerCallPtr call;
    CORE::CString sessionKey;
    UInt32 intervalMs;
    bool includeThreads;
    bool includeTasks;
    bool includeScheduledJobs;
    UInt64 lastSentMs;
    bool hasPending;
    COMCORE::CRpcMessage pending;
    UInt64 samplesWritten;
    UInt64 samplesSkipped;

    CTaskManagerWatchStream( void );
};

