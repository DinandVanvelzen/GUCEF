    TDrnUtilsCommandStatus status;
    CORE::CString statusMessage;
    bool replayed;
    UInt64 revision;
    UInt64 runId;
    CORE::CString::StringVector messages;
    bool hasRun;
    CORE::SJobRunRecord run;            /**< RUN_NOW with waitForRun: the final run */
