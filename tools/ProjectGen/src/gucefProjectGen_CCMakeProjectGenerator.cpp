void
WriteCMakeListsFilesToDisk( const CProjectInfo& projectInfo  ,
                            const CORE::CString& logFilename ,
                            bool treatTagsAsOptions          ,
                            bool addCompileDate = false      )
{GUCEF_TRACE;

    // Write all the CMakeLists.txt files
    TStringToModuleInfoEntryPtrMap::const_iterator i = projectInfo.modules.begin();
    while ( i != projectInfo.modules.end() )
    {
        const CModuleInfoEntryPtr& moduleInfoEntry = (*i).second;
        if ( !moduleInfoEntry->HasOnlyLogicalModuleType() )
        {
            CORE::CString fileContent = GenerateCMakeListsFileContent( projectInfo, moduleInfoEntry, treatTagsAsOptions, addCompileDate );
            if ( logFilename.Length() > 0 )
            {
                fileContent += "\n# Generator logfile can be found at: " + logFilename;
            }

            CORE::CString pathToCMakeListsFile = moduleInfoEntry->GetAbsolutePathToModuleRootDir();
            CORE::AppendToPath( pathToCMakeListsFile, "CMakeLists.txt" );

            if ( CORE::WriteStringAsTextFile( pathToCMakeListsFile, fileContent, true, "\n", true ) )
            {
                GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "Created CMakeLists.txt file for project dir: " + moduleInfoEntry->GetAbsolutePathToModuleRootDir() );
            }
            else
            {
                GUCEF_ERROR_LOG( CORE::LOGLEVEL_IMPORTANT, "Failed to write CMakeLists.txt file content to disk at path " + moduleInfoEntry->GetAbsolutePathToModuleRootDir() );
            }
        }
        else
        {
            TModuleType allPlatformsType = moduleInfoEntry->GetModuleType( KnownPlatforms::AllPlatforms );
            GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "Skipping CMakeLists.txt generation for module of type \"" + ModuleTypeToString( allPlatformsType ) + "\"" );
        }
        ++i;
    }
}
