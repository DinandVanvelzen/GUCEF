CORE::CString
GenerateGithubActionsWorkflowProjectSection( const CORE::CString& targetName                  ,
                                             const CORE::CString& targetPlatform              ,
                                             const CORE::CString& runsOnPlatform              ,
                                             const CORE::CString& productName                 ,
                                             const CORE::CString& pathToTargetsOutputDir      ,
                                             const CORE::CString& pathToCMakeTargetsOutputDir ,
                                             bool useWorkflowEventDispatch                    )
{GUCEF_TRACE;

    CORE::CString section;
    CORE::CString osPathToTargetsOutputDir;
    CORE::CString osPathToCMakeTargetsProjectDir;
    CORE::CString workflowRunsOnPlatform;

    if ( "linux32" == targetPlatform || "linux64" == targetPlatform || KnownPlatforms::AllPlatforms == targetPlatform )
    {
        // Change cmake relative path dir sep to match linux
        osPathToTargetsOutputDir = pathToTargetsOutputDir.ReplaceChar( '\\', '/' );
        osPathToCMakeTargetsProjectDir = pathToCMakeTargetsOutputDir.ReplaceChar( '\\', '/' ) + '/' + targetName;
        
        workflowRunsOnPlatform = "ubuntu-latest";
        if ( !runsOnPlatform.IsNULLOrEmpty() )
            workflowRunsOnPlatform = runsOnPlatform;    

        section = "  $workflowId$:\n"
                  "$workflowRunCondition$"
                  "    runs-on: $workflowRunsOnPlatform$\n"
                  "    env:\n"
                  "      TARGET_NAME: $targetName$\n"
                  "      TARGET_PLATFORM: $targetPlatform$\n"
                  "      TARGET_PROJECT: $targetProject$\n"
                  "      PRODUCT_NAME: $productName$\n"
                  "      CI_TOOL: GITHUB-ACTIONS\n"
                  "      BUILD_TOOL: CMAKE\n"
                  "    steps:\n"
                  "      - uses: actions/checkout@master\n"
                  "      - name: Build $productName$ for platform $targetPlatform$\n"                  
                  "        run: ./$pathToTargetsOutputDir$/ci_build.sh\n"
                  "      - name: Archive Debian build artifacts\n"
                  "        uses: actions/upload-artifact@v2\n"
                  "        with:\n"
                  "          name: Debian packages\n"
                  "          path: |\n"
                  "            ./common/bin/$targetName$-$targetPlatform$/packages/*$productName$*.deb\n"
                  "      - name: Archive RPM build artifacts\n"
                  "        uses: actions/upload-artifact@v2\n"
                  "        with:\n"
                  "          name: RPM packages\n"
                  "          path: |\n"
                  "            ./common/bin/$targetName$-$targetPlatform$/packages/*$productName$*.rpm\n"
                  "      - name: Archive Tarball - bz2 compressed build artifacts\n"
                  "        uses: actions/upload-artifact@v2\n"
                  "        with:\n"
                  "          name: tar.bz2 packages\n"
                  "          path: |\n"
                  "            ./common/bin/$targetName$-$targetPlatform$/packages/*$productName$*.tar.bz2\n"
                  "      - name: Archive Tarball - Xz compressed build artifacts\n"
                  "        uses: actions/upload-artifact@v2\n"
                  "        with:\n"
                  "          name: tar.xz packages\n"
                  "          path: |\n"
                  "            ./common/bin/$targetName$-$targetPlatform$/packages/*$productName$*.tar.xz\n";
    }
    else
    if ( "win32" == targetPlatform || "win64" == targetPlatform )
    {
        // Change cmake relative path dir sep to match windows
        osPathToTargetsOutputDir = pathToTargetsOutputDir.ReplaceChar( '/', '\\' );
        osPathToCMakeTargetsProjectDir = pathToCMakeTargetsOutputDir.ReplaceChar( '/', '\\' ) + '\\' + targetName;

        workflowRunsOnPlatform = "windows-latest";
        if ( !runsOnPlatform.IsNULLOrEmpty() )
            workflowRunsOnPlatform = runsOnPlatform; 
        
        section = "  $workflowId$:\n"
                  "$workflowRunCondition$"
                  "    runs-on: $workflowRunsOnPlatform$\n"
                  "    env:\n"
                  "      TARGET_NAME: $targetName$\n"
                  "      TARGET_PLATFORM: $targetPlatform$\n"
                  "      TARGET_PROJECT: $targetProject$\n"
                  "      PRODUCT_NAME: $productName$\n"
                  "      CI_TOOL: GITHUB-ACTIONS\n"
                  "      BUILD_TOOL: CMAKE\n"
                  "    steps:\n"
                  "      - uses: actions/checkout@master\n"
                  "      - name: Build $productName$ for platform $targetPlatform$\n"
                  "        run: .\\$pathToTargetsOutputDir$\\ci_build.ps1\n"
                  "      - name: Archive ZIP build artifacts\n"
                  "        uses: actions/upload-artifact@v2\n"
                  "        with:\n"
                  "          name: ZIP packages\n"
                  "          path: |\n"
                  "            ./common/bin/$targetName$-$targetPlatform$/packages/*$productName$*.zip\n";
    }
    
    if ( !section.IsNULLOrEmpty() )
    {
        CORE::CString workflowPermittedId = GenerateValidGithubActionsWorkflowId( targetName, targetPlatform );

        CORE::CString workflowRunCondition;    
        if ( !useWorkflowEventDispatch )
        {
            workflowRunCondition = "    if: github.event.client_payload.job == '$targetName$-$targetPlatform$'\n";
        }

        section = section.ReplaceSubstr( "$workflowRunCondition$", workflowRunCondition );
        section = section.ReplaceSubstr( "$workflowRunsOnPlatform$", workflowRunsOnPlatform );        
        section = section.ReplaceSubstr( "$workflowId$", workflowPermittedId );
        section = section.ReplaceSubstr( "$targetName$", targetName ); 
        section = section.ReplaceSubstr( "$targetPlatform$", targetPlatform ); 
        section = section.ReplaceSubstr( "$productName$", productName ); 
        section = section.ReplaceSubstr( "$targetProject$", osPathToCMakeTargetsProjectDir ); 
        section = section.ReplaceSubstr( "$pathToTargetsOutputDir$", osPathToTargetsOutputDir );
        
        return section;
    }
    return CORE::CString::Empty; 
}

