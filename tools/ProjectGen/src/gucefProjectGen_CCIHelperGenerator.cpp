void
GenerateGithubActionsWorkflowTargetsYml( const CProjectInfo& projectInfo                  ,
                                         const CProjectTargetInfoBundle& targets          ,
                                         const CORE::CString::StringSet& platformFilter   ,
                                         const CORE::CString& targetsOutputDir            ,
                                         const CORE::CString& cmakeTargetsOutputDir       ,
                                         bool useWorkflowEventDispatch                    ,
                                         bool useSelfHostedRunner                         ,
                                         bool prefixWorkflowFilenameWithProjectGenAutoGen )
{GUCEF_TRACE;

    // We need the relative path not absolute for the yml
    CORE::CString pathToTargetsOutputDir = GetShortestRelativePathFromAbsPathToProjectRoot( projectInfo, targetsOutputDir );
    CORE::CString pathToCMakeTargetsOutputDir = GetShortestRelativePathFromAbsPathToProjectRoot( projectInfo, cmakeTargetsOutputDir );
    
    TStringVector::const_iterator m = projectInfo.rootDirs.begin();
    while ( m != projectInfo.rootDirs.end() )
    {
        CORE::CString githubActionsWorkflowTargetYmlPath = CORE::CombinePath( (*m), ".github/workflows/" );
        githubActionsWorkflowTargetYmlPath = githubActionsWorkflowTargetYmlPath.ReplaceChar( GUCEF_DIRSEPCHAROPPOSITE, GUCEF_DIRSEPCHAR );

        if ( !CORE::CreateDirs( githubActionsWorkflowTargetYmlPath ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_NORMAL, "GenerateGithubActionsWorkflowProjectsYml: Failed to create directories. Dir path: " + githubActionsWorkflowTargetYmlPath );
            ++m;
            continue;
        }

        ++m;
    }

    CProjectTargetInfoBundle::TProjectTargetInfoPtrMapMap::const_iterator i = targets.GetAllTargets().begin();
    while ( i != targets.GetAllTargets().end() )
    {
        const CORE::CString& targetName = (*i).first;
        const CProjectTargetInfoBundle::TProjectTargetInfoPtrMap& targetsPerPlatform = (*i).second;

        CORE::CString githubActionsWorkflowTargetContent;
        if ( useWorkflowEventDispatch )
        {
            githubActionsWorkflowTargetContent =
                "name: target_" + targetName + "\n"             
                "\n"                           
                "on:\n"
                "  workflow_dispatch:\n"    
                "    inputs:\n"
                "      archiveBuildArtifacts:\n"
                "        description: 'Archive Build Artifacts?'\n"
                "        required: false\n"
                "        default: 'false'\n"
                "      targetPlatform:\n"
                "        description: 'Target platform to build?'\n"
                "        required: false\n"
                "        default: 'all'\n"
                "\n"                           
                "jobs:\n"                      
                "\n";
        }
        else
        {
            githubActionsWorkflowTargetContent =
                "name: target_" + targetName + "\n"             
                "\n"                           
                "on: repository_dispatch\n"    
                "\n"                           
                "jobs:\n"                      
                "\n";
        }

        CProjectTargetInfoBundle::TProjectTargetInfoPtrMap::const_iterator n = targetsPerPlatform.begin();
        while ( n != targetsPerPlatform.end() )
        {
            const CORE::CString& platformName = (*n).first;
            if ( platformFilter.find( platformName ) != platformFilter.end() )
            {
                const CProjectTargetInfoPtr& targetInfo = (*n).second;

                CORE::CString productName;
                if ( targetInfo->mainModule.IsNULL() )
                {
                    productName = targetInfo->projectName;
                }
                else
                {
                    productName = targetInfo->mainModule->GetConsensusName();
                }
            
                CORE::CString runsOnPlatform = useSelfHostedRunner ? "self-hosted" : CORE::CString::Empty;
                CORE::CString section = GenerateGithubActionsWorkflowProjectSection( targetInfo->projectName, platformName, runsOnPlatform, productName, pathToTargetsOutputDir, pathToCMakeTargetsOutputDir, useWorkflowEventDispatch ); 
                if ( !section.IsNULLOrEmpty() )
                {
                    githubActionsWorkflowTargetContent += section;
                    GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "GenerateGithubActionsWorkflowProjectsYml: Generated Github Actions Workflow job to build target \"" + targetName + "\" with project name \"" + targetInfo->projectName + "\" and platform \"" + platformName + "\"" );
                }
                else
                {
                    // not supported atm
                    GUCEF_WARNING_LOG( CORE::LOGLEVEL_NORMAL, "GenerateGithubActionsWorkflowProjectsYml: Could not generate Github Actions Workflow job to build target \"" + targetName + "\" with project name \"" + targetInfo->projectName + "\" and platform \"" + platformName + "\"" );
                }
            }
            ++n;
        }

        TStringVector::const_iterator m = projectInfo.rootDirs.begin();
        while ( m != projectInfo.rootDirs.end() )
        {
            CORE::CString githubActionsWorkflowTargetYmlPath = CORE::CombinePath( (*m), ".github/workflows/" );
            githubActionsWorkflowTargetYmlPath = githubActionsWorkflowTargetYmlPath.ReplaceChar( GUCEF_DIRSEPCHAROPPOSITE, GUCEF_DIRSEPCHAR );
            
            CORE::CString workflowYml;
            if ( prefixWorkflowFilenameWithProjectGenAutoGen )
                workflowYml = "projectgen.autogen." + targetName + ".yml";  // this makes the names rather long but does help to namespace autogenerated workflows
            else
                workflowYml = targetName + ".yml";

            githubActionsWorkflowTargetYmlPath = CORE::CombinePath( githubActionsWorkflowTargetYmlPath, workflowYml );

            if ( CORE::WriteStringAsTextFile( githubActionsWorkflowTargetYmlPath, githubActionsWorkflowTargetContent ) )
            {
                GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "GenerateGithubActionsWorkflowProjectsYml: Successfully wrote Github Actions Workflow file with project jobs to: " + githubActionsWorkflowTargetYmlPath );
            }
            else
            {
                GUCEF_ERROR_LOG( CORE::LOGLEVEL_NORMAL, "GenerateGithubActionsWorkflowProjectsYml: Failed to write Github Actions Workflow file with project jobs to: " + githubActionsWorkflowTargetYmlPath );
            }

            ++m;
        }

        ++i;
    }
}

