// Why generate the bash script here?
//  because we tie together knowledge of the bash script and the CI tooling in the way we auto configured it
//  we need both to be in sync for this to work due to environment variables being passed around
bool
GenerateCIBuildBashScript( const CORE::CString& targetsOutputDir )
{GUCEF_TRACE;
 
    CORE::CString bashScript =
    "#!/bin/bash\n"
    "#\n"
    "#  AUTO GENERATED BY PROJECTGENERATOR CI HELPER\n"
    "#\n\n"
    "# Provide easy access to the location of the script dir itself\n"
    "DIR=\"$(cd \"${0%/*}\" 2>/dev/null; echo \"$PWD\"/\"${0##*/}\")\""
    "\n\n"
    "# Provide the environment variables for troubleshooting\n"
    "echo -e \"TARGET_NAME: $TARGET_NAME\\n"
              "TARGET_PLATFORM: $TARGET_PLATFORM\\n"
              "TARGET_PROJECT: $TARGET_PROJECT\\n"
              "PRODUCT_NAME: $PRODUCT_NAME\\n"
              "CI_TOOL: $CI_TOOL\\n"
              "BUILD_TOOL: $BUILD_TOOL\\n"
              "BUILD_TYPE: $BUILD_TYPE\\n\"\n\n"
    "# Provide the CI tooling specific environment variables for troubleshooting\n"
    "if [[ ${CI_TOOL} == \"GITHUB-ACTIONS\" ]]; then\n"
    "    echo -e \"CI: $CI\\n"
                  "GITHUB_WORKFLOW: $GITHUB_WORKFLOW\\n"
                  "GITHUB_RUN_ID: $GITHUB_RUN_ID\\n"
                  "GITHUB_RUN_NUMBER: $GITHUB_RUN_NUMBER\\n"
                  "GITHUB_JOB: $GITHUB_JOB\\n"
                  "GITHUB_ACTION: $GITHUB_ACTION\\n"
                  "GITHUB_ACTION_PATH: $GITHUB_ACTION_PATH\\n"
                  "GITHUB_ACTIONS: $GITHUB_ACTIONS\\n"
                  "GITHUB_ACTOR: $GITHUB_ACTOR\\n"
                  "GITHUB_REPOSITORY: $GITHUB_REPOSITORY\\n"
                  "GITHUB_EVENT_NAME: $GITHUB_EVENT_NAME\\n"
                  "GITHUB_EVENT_PATH: $GITHUB_EVENT_PATH\\n"
                  "GITHUB_WORKSPACE: $GITHUB_WORKSPACE\\n"
                  "GITHUB_SHA: $GITHUB_SHA\\n"
                  "GITHUB_REF: $GITHUB_REF\\n"
                  "GITHUB_HEAD_REF: $GITHUB_HEAD_REF\\n"
                  "GITHUB_BASE_REF: $GITHUB_BASE_REF\\n"
                  "GITHUB_SERVER_URL: $GITHUB_SERVER_URL\\n"
                  "GITHUB_API_URL: $GITHUB_API_URL\\n"
                  "GITHUB_GRAPHQL_URL: $GITHUB_GRAPHQL_URL\\n"
                  "RUNNER_OS: $RUNNER_OS\\n"
                  "RUNNER_TOOL_CACHE: $RUNNER_TOOL_CACHE\\n\"\n"
    "    REPO_ROOT=$GITHUB_WORKSPACE\n"
    "else\n"
    "    echo \"Unknown CI Tooling\"\n"
    "fi\n"
    "\n\n"
    "if [[ -z \"$BUILD_TOOL\" ]]; then\n"
    "    echo \"Build tool was not specified. Will default to CMake\"\n"
    "    BUILD_TOOL=\"CMAKE\"\n"
    "fi\n"
    "\n\n"
    "if [[ -z \"$BUILD_TYPE\" ]]; then\n"
    "    echo \"Build type was not specified. Will default to 'release'\"\n"
    "    BUILD_TYPE=\"release\"\n"
    "fi\n"
    "\n\n"
    "if [[ ${BUILD_TOOL} == \"CMAKE\" ]]; then\n"
    "    cmake -H\"$REPO_ROOT/$TARGET_PROJECT\" -B\"$REPO_ROOT/common/bin/$TARGET_NAME-$TARGET_PLATFORM\" -DCMAKE_BUILD_TYPE=$BUILD_TYPE\n" 
    "    cmake --build \"$REPO_ROOT/common/bin/$TARGET_NAME-$TARGET_PLATFORM\"\n" 
    "    cmake --install \"$REPO_ROOT/common/bin/$TARGET_NAME-$TARGET_PLATFORM\" --prefix instdir --strip\n"
    "    cpack --config \"$REPO_ROOT/common/bin/$TARGET_NAME-$TARGET_PLATFORM/CPackConfig.cmake\"\n"
    "else\n"
    "    echo \"Unknown Build tool\"\n"
    "fi\n\n";
    
    if ( !CORE::CreateDirs( targetsOutputDir ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_NORMAL, "GenerateCIBuildBashScript: Failed to create directories. Dir path: " + targetsOutputDir );
        return false;
    }

    CORE::CString bashScriptPath = CORE::CombinePath( targetsOutputDir, "ci_build.sh" );
    if ( CORE::WriteStringAsTextFile( bashScriptPath, bashScript ) )
    {
        GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "GenerateCIBuildBashScript: Successfully wrote CI Bash script to: " + bashScriptPath );
        return true;
    }
    else
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_NORMAL, "GenerateCIBuildBashScript: Failed to write CI Bash script to: " + bashScriptPath );
    }
    return false;
}

