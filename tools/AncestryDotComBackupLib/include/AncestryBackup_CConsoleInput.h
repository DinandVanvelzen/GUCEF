/**
 *  Reads what the user types without blocking, so the program can go on pumping events while it waits
 *  for the user to press Enter.
 */
class CConsoleInput
{
    public:

    CConsoleInput( void );

    /**
     *  Collects what has been typed so far.
     *  @param line     receives the line when Enter was pressed
     *  @return true if a complete line was read
     */
    bool PollLine( std::string& line );

    /** Is there a console to read from? When input is closed or redirected from /dev/null there is nobody to wait for */
    bool IsInputClosed( void ) const;

    private:

    std::string m_pending;
    bool m_closed;
};

