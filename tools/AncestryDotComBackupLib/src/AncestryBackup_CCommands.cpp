int
CCommands::Media( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    if ( !layout.IsValid() )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The data directory or tree id is not valid" );
        return EXIT_CODE_USAGE;
    }
    std::string siteTreeId, treeIdOrigin;
    if ( !ResolveSiteTreeId( settings, layout, siteTreeId, treeIdOrigin ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The id Ancestry uses for the tree is not known, give siteTreeId or run the export command first" );
        return EXIT_CODE_USAGE;
    }

    const CORE::CString inventoryFile = CORE::CombinePath( layout.GetStateDir(), "media-inventory.jsonl" );
    const CORE::CString failedFile = CORE::CombinePath( layout.GetStateDir(), "media-failed.txt" );
    const CORE::CString listDir = CORE::CombinePath( layout.GetRawDir(), "media-lists" );
    CORE::CreateDirs( layout.GetStateDir() );
    CORE::CreateDirs( layout.GetMediaDir() );
    CORE::CreateDirs( listDir );

    CBrowserSession session( settings, layout, siteTreeId );
    if ( !session.Open() )
        return EXIT_CODE_BROWSER;

    std::vector< SMediaItem > items;
    std::set< std::string > ids;
    LoadInventory( inventoryFile, items, ids );
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: The inventory holds " + CORE::UInt32ToString( (UInt32) items.size() ) + " items so far" );

    // what is on the site: every kind of media has a list of its own, 28 items to a page
    const UInt32 rows = 28;
    const std::vector< std::string > filters = CMediaInventory::GetFilters();
    for ( size_t f=0; f<filters.size(); ++f )
    {
        UInt32 total = 0;
        const CORE::CString completeMarker = CORE::CombinePath( layout.GetStateDir(), CORE::CString( "media-list-" ) + filters[ f ].c_str() + "-complete.txt" );
        const bool wasComplete = CORE::FileExists( completeMarker );
        const CORE::CString progressFile = CORE::CombinePath( layout.GetStateDir(), CORE::CString( "media-list-" ) + filters[ f ].c_str() + "-page.txt" );
        UInt32 startPage = 1;
        if ( !wasComplete )
        {
            // a run that was cut short goes on where it stopped
            std::string progress;
            ReadAll( progressFile, progress );
            if ( progress.compare( 0, 5, "page=" ) == 0 )
                startPage = (UInt32) strtoul( progress.c_str() + 5, GUCEF_NULL, 10 ) + 1;
        }
        bool budgetEnded = false;
        for ( UInt32 page = startPage; ; ++page )
        {
            SFetchResult response;
            if ( !session.GetText( CMediaInventory::BuildListUrl( siteTreeId, filters[ f ], page, rows ), true, response ) )
            {
                if ( response.error.compare( 0, 9, "no more r" ) == 0 )
                {
                    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Stopping for this run: " + CORE::CString( response.error.c_str() ) );
                    budgetEnded = true;
                    break;
                }
                GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Could not read the list of " + CORE::CString( filters[ f ].c_str() ) + " media: " + CORE::CString( response.error.c_str() ) );
                return response.halted ? EXIT_CODE_HALTED : EXIT_CODE_FAILED;
            }
            CORE::CDataNode document;
            SMediaPage listed;
            if ( !COM::CJsonRpcEndpoint::ParseJsonText( CORE::CString( response.body.c_str() ), document ) || !CMediaInventory::ParsePage( document, listed, &SerializeNode ) )
            {
                GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The list of media did not answer in the form that is known" );
                return EXIT_CODE_FAILED;
            }
            total = listed.totalCount;
            CORE::WriteStringAsTextFile( CORE::CombinePath( listDir, CORE::CString( filters[ f ].c_str() ) + "-" + CORE::UInt32ToString( page ) + ".json" ), CORE::CString( response.body.c_str() ) );

            std::string lines;
            UInt32 added = 0;
            for ( size_t i=0; i<listed.items.size(); ++i )
                if ( ids.insert( listed.items[ i ].id ).second )
                {
                    lines += CMediaInventory::ToInventoryLine( listed.items[ i ] ) + "\n";
                    items.push_back( listed.items[ i ] );
                    ++added;
                }
            if ( !lines.empty() && !AppendTo( inventoryFile, lines ) )
            {
                GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + inventoryFile );
                return EXIT_CODE_FAILED;
            }
            CORE::WriteStringAsTextFile( progressFile, CORE::CString( ( "page=" + std::to_string( (unsigned long long) page ) + "\n" ).c_str() ) );

            // The list is newest first. Once all of it has been read at some time only the pages with something new in them matter,
            // before that every page counts, also when a run was cut short and pages were seen before
            if ( listed.items.size() < rows || page * rows >= total )
            {
                CORE::WriteStringAsTextFile( completeMarker, CORE::CString( ( "total=" + std::to_string( (unsigned long long) total ) + "\n" ).c_str() ) );
                break;
            }
            if ( wasComplete && added == 0 )
                break;
        }
        GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "AncestryBackup: " + CORE::CString( filters[ f ].c_str() ) + ": " + CORE::UInt32ToString( total ) + " on the site" );
        if ( budgetEnded )
            break;
    }

    // photos the site could not find a file for are not asked for again and again, they are listed in media-missing.txt
    const CORE::CString missingFile = CORE::CombinePath( layout.GetStateDir(), "media-missing.txt" );
    std::set< std::string > missing;
    {
        std::string text;
        ReadAll( missingFile, text );
        size_t pos = 0;
        while ( pos < text.size() )
        {
            size_t end = text.find( '\n', pos );
            if ( end == std::string::npos )
                end = text.size();
            const std::string line = text.substr( pos, end - pos );
            const size_t tab = line.find( '\t' );
            if ( !line.empty() )
                missing.insert( tab == std::string::npos ? line : line.substr( 0, tab ) );
            pos = end + 1;
        }
    }

    // The files. Items that have image data on the site come first. Items without are often placeholders left by a bulk import which
    // have no file at all, those are tried at the end, once each.
    {
        std::vector< SMediaItem > withDimensions, withoutDimensions;
        for ( size_t i=0; i<items.size(); ++i )
            ( items[ i ].width.empty() ? withoutDimensions : withDimensions ).push_back( items[ i ] );
        items = withDimensions;
        items.insert( items.end(), withoutDimensions.begin(), withoutDimensions.end() );
    }
    UInt32 fetched = 0, skippedKinds = 0, failed = 0, present = 0, knownMissing = 0;
    UInt64 bytes = 0;
    for ( size_t i=0; i<items.size(); ++i )
    {
        const SMediaItem& item = items[ i ];
        if ( !CMediaInventory::IsDownloadable( item ) )
        {
            ++skippedKinds;
            continue;
        }
        const CORE::CString path = CORE::CombinePath( layout.GetMediaDir(), CMediaInventory::FileNameOf( item ).c_str() );
        if ( CORE::FileExists( path ) )
        {
            ++present;
            continue;
        }
        if ( !settings.retryMissing && missing.find( item.id ) != missing.end() )
        {
            ++knownMissing;
            continue;
        }

        SFetchResult response;
        bool got = session.GetToFile( CMediaInventory::BuildDownloadUrl( item ), path, response );

        // some files are not found at the full size address but are at the address the list itself gives
        if ( !got && !response.halted && response.status == 404 && !item.width.empty() && !CMediaInventory::BuildSiteUrl( item ).empty() )
        {
            SFetchResult second;
            got = session.GetToFile( CMediaInventory::BuildSiteUrl( item ), path, second );
            response = second;
        }
        if ( !got )
        {
            if ( response.halted )
                return EXIT_CODE_HALTED;
            if ( response.error.compare( 0, 9, "no more r" ) == 0 )
            {
                GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Stopping for this run: " + CORE::CString( response.error.c_str() ) );
                break;
            }
            ++failed;
            AppendTo( failedFile, item.id + "\t" + response.error + "\n" );
            if ( response.status == 404 )
                AppendTo( missingFile, item.id + "\tnot found at either address\n" );
            continue;
        }

        // an answer that is not a file, such as a page with an error on it, is not kept
        const std::string type = response.contentType;
        if ( type.compare( 0, 6, "image/" ) != 0 && type.compare( 0, 15, "application/pdf" ) != 0 && type.compare( 0, 24, "application/octet-stream" ) != 0 )
        {
            CORE::DeleteFile( path );
            ++failed;
            AppendTo( failedFile, item.id + "\tunexpected content type " + type + "\n" );
            continue;
        }

        // the metadata next to the file: everything the site said about it, and what we did
        CORE::WriteStringAsTextFile( path + ".json", CORE::CString( ( "{\"downloaded\":\"" + CChangeFeed::FormatTime( CORE::CDateTime::NowUTCDateTime().ToUnixEpochBasedTicksInMillisecs() ) +
                                                                  "\",\"bytes\":" + std::to_string( (unsigned long long) response.bytes ) + ",\"contentType\":\"" + type + "\",\"item\":" +
                                                                  ( item.json.empty() ? std::string( "null" ) : item.json ) + "}" ).c_str() ) );
        ++fetched;
        bytes += response.bytes;
        if ( fetched % 25 == 0 )
            GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "AncestryBackup: Downloaded " + CORE::UInt32ToString( fetched ) + " files so far" );
    }

    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Media: " + CORE::UInt32ToString( (UInt32) items.size() ) + " in the inventory, " + CORE::UInt32ToString( fetched ) + " downloaded now (" +
                                         CORE::UInt64ToString( bytes / 1024 ) + " KiB), " + CORE::UInt32ToString( present ) + " were here already, " + CORE::UInt32ToString( failed ) + " failed (see " + failedFile + "), " + CORE::UInt32ToString( knownMissing ) + " are known to be missing on the site (" + missingFile +
                                         "), " + CORE::UInt32ToString( skippedKinds ) + " are not pictures or documents and were not downloaded" );
    return EXIT_CODE_OK;
}

