int
CCommands::Login( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    if ( !layout.CreateDiscoveryDirs() )
        return EXIT_CODE_USAGE;

    CChromeBrowser browser;
    ConfigureBrowser( settings, layout, browser );
    if ( !browser.EnsureRunning( settings.startUrl ) )
        return EXIT_CODE_BROWSER;

    WEB::CChromeDevToolsClient client;
    if ( !browser.ConnectToBrowser( client ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to connect to the browser" );
        return EXIT_CODE_BROWSER;
    }

    // a tab to work in: one that is on the site already, or else a new one. Never a tab of the user's that shows something else.
    CORE::CDataNode targets;
    CORE::CString targetId;
    if ( client.SendCommandAndWait( "Target.getTargets", GUCEF_NULL, targets ) )
    {
        const CORE::CDataNode* infos = targets.Find( "targetInfos" );
        if ( GUCEF_NULL != infos )
        {
            for ( CORE::CDataNode::const_iterator i = infos->ConstBegin(); i != infos->ConstEnd(); ++i )
            {
                if ( (*i)->GetAttributeValue( "type" ).AsString() != "page" )
                    continue;
                if ( (*i)->GetAttributeValue( "url" ).AsString().HasSubstr( settings.cookieDomain ) >= 0 )
                    targetId = (*i)->GetAttributeValue( "targetId" ).AsString();
            }
        }
    }
    if ( targetId.IsNULLOrEmpty() && !client.TargetCreate( settings.startUrl, targetId ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The browser has no tab to log in with" );
        return EXIT_CODE_BROWSER;
    }

    CORE::CString sessionId;
    if ( !client.AttachToTarget( targetId, sessionId ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to attach to the tab" );
        return EXIT_CODE_BROWSER;
    }
    client.SetSessionId( sessionId );

    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Log in to the site in the browser window if you are not logged in yet. Any 2 step verification or captcha works as usual, we never see your password." );
    if ( !settings.noWait )
    {
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Press Enter here when you are logged in and the site shows your tree." );
        CConsoleInput input;
        std::string line;
        while ( !IsStopRequested() && !input.PollLine( line ) )
        {
            if ( input.IsInputClosed() )
                break;
            Pump( 20 );
            if ( !client.IsConnected() )
            {
                GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The browser was closed" );
                return EXIT_CODE_BROWSER;
            }
        }
    }

    client.NetworkEnable();
    std::vector< WEB::SChromeCookie > cookies;
    if ( !client.GetAllCookies( cookies ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The browser would not tell what cookies it has" );
        return EXIT_CODE_FAILED;
    }

    UInt32 total = 0, secure = 0, httpOnly = 0, session = 0;
    std::string names;
    for ( size_t i=0; i<cookies.size(); ++i )
    {
        if ( !EndsWithNoCase( cookies[ i ].domain.STL_String().c_str(), settings.cookieDomain.STL_String().c_str() ) )
            continue;
        ++total;
        if ( cookies[ i ].secure ) ++secure;
        if ( cookies[ i ].httpOnly ) ++httpOnly;
        if ( cookies[ i ].session ) ++session;
        names += ( names.empty() ? "" : ", " ) + std::string( cookies[ i ].name.STL_String().c_str() );
    }

    CORE::CDataNode title;
    client.RuntimeEvaluate( "document.title + ' | ' + location.href", false, title );
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: The tab shows: " + title.GetValue().AsString() );
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: The browser holds " + CORE::UInt32ToString( total ) + " cookies of " + settings.cookieDomain +
                                         " (" + CORE::UInt32ToString( httpOnly ) + " HttpOnly, " + CORE::UInt32ToString( secure ) + " secure, " + CORE::UInt32ToString( session ) + " session)" );
    GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "AncestryBackup: Cookie names: " + CORE::CString( names.c_str() ) );

    if ( total == 0 )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The browser holds no cookies of the site, you are not logged in" );
        return EXIT_CODE_NOT_LOGGED_IN;
    }
    if ( browser.IsAttached() )
    {
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Done. Your own browser was used, the tool keeps no login of its own." );
    }
    else
    {
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: The browser stays open, the login lives in its profile at " + layout.GetBrowserProfileDir() );
    }
    return EXIT_CODE_OK;
}

