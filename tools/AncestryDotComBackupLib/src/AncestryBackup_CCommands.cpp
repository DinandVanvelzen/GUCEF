int
CCommands::ImportGedcom( const CDataLayout& layout, const CORE::CString& source, bool copyIn, UInt64 sourceModifiedInMs )
{GUCEF_TRACE;

    const CORE::CString destination = layout.GetBaselineGedcomPath();

    std::vector< char > content;
    if ( !ReadFile( source, content ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to read " + source );
        return EXIT_CODE_FAILED;
    }

    CGedcomSummarizer summarizer;
    CGedcomReader::Parse( content.empty() ? "" : &content[ 0 ], content.size(), summarizer );
    const SGedcomSummary& summary = summarizer.GetSummary();
    if ( !summary.hasHeader || summary.individuals == 0 )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: " + source + " does not look like a GEDCOM file of a tree: it has " +
                                                  CORE::UInt32ToString( summary.individuals ) + " individuals" + ( summary.hasHeader ? "" : " and no header" ) );
        return EXIT_CODE_FAILED;
    }

    // into the data of the tree, as the latest and as a copy of its own to compare later exports with
    if ( copyIn && source != destination )
    {
        if ( sourceModifiedInMs == 0 )
            sourceModifiedInMs = CORE::GetFileModificationTime( source ).ToUnixEpochBasedTicksInMillisecs();
        const CORE::CString snapshot = CORE::CombinePath( layout.GetBaselineSnapshotsDir(), "export-" + CExportFinder::FormatTimestamp( sourceModifiedInMs ) + ".ged" );
        if ( !CORE::CreateDirs( layout.GetTreeDir() ) || !CORE::CreateDirs( layout.GetBaselineSnapshotsDir() ) ||
             !WriteFileInPlace( destination, content ) || !WriteFileInPlace( snapshot, content ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to copy the GEDCOM file to " + destination );
            return EXIT_CODE_FAILED;
        }
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Copied the GEDCOM file to " + destination + " and kept it as " + snapshot );
    }

    const CORE::CString report = CGedcomSummarizer::Render( summary );
    std::string ids;
    for ( size_t i=0; i<summary.individualIds.size(); ++i )
        ids += summary.individualIds[ i ] + "\n";
    if ( !CORE::CreateDirs( layout.GetStateDir() ) ||
         !CORE::WriteStringAsTextFile( CORE::CombinePath( layout.GetStateDir(), "baseline-summary.txt" ), report ) ||
         !CORE::WriteStringAsTextFile( CORE::CombinePath( layout.GetStateDir(), "baseline-individuals.txt" ), CORE::CString( ids.c_str() ) ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write the summary to " + layout.GetStateDir() );
        return EXIT_CODE_FAILED;
    }

    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: The GEDCOM file holds " + CORE::UInt32ToString( summary.individuals ) + " individuals, " + CORE::UInt32ToString( summary.families ) +
                                         " families, " + CORE::UInt32ToString( summary.sources ) + " sources and " + CORE::UInt32ToString( summary.mediaFiles ) + " media files. The summary is in " +
                                         CORE::CombinePath( layout.GetStateDir(), "baseline-summary.txt" ) );
    return EXIT_CODE_OK;
}

/*-------------------------------------------------------------------------*/

int
CCommands::ImportZip( const CDataLayout& layout, const CORE::CString& zipPath, UInt64 zipModifiedInMs )
{GUCEF_TRACE;

    if ( zipModifiedInMs == 0 )
        zipModifiedInMs = CORE::GetFileModificationTime( zipPath ).ToUnixEpochBasedTicksInMillisecs();

    // the file comes out next to the data of the tree and is gone again once it is taken in
    const CORE::CString workDir = CORE::CombinePath( layout.GetStateDir(), "unzipped" );
    CORE::CString extracted;
    if ( !CZipExtractor::ExtractFirst( zipPath, ".ged", workDir, extracted ) )
        return EXIT_CODE_FAILED;

    const int result = ImportGedcom( layout, extracted, true, zipModifiedInMs );
    CORE::DeleteFile( extracted );
    return result;
}

/*-------------------------------------------------------------------------*/

int
CCommands::Baseline( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    if ( !layout.IsValid() )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The data directory or tree id is not valid" );
        return EXIT_CODE_USAGE;
    }

    const bool given = !settings.baselineGedcom.IsNULLOrEmpty();
    const CORE::CString source = given ? CORE::RelativePath( settings.baselineGedcom ) : layout.GetBaselineGedcomPath();
    if ( !CORE::FileExists( source ) )
    {
        if ( given )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The GEDCOM file " + source + " does not exist" );
        }
        else
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: No GEDCOM file was given (gedcom=<file>) and none was imported before" );
        }
        return EXIT_CODE_USAGE;
    }
    if ( given && EndsWithNoCase( source.STL_String(), ".zip" ) )
        return ImportZip( layout, source, 0 );
    return ImportGedcom( layout, source, given, 0 );
}

