/** Reads a whole file, the text of a GEDCOM file is parsed in place */
static bool
ReadFile( const CORE::CString& path, std::vector< char >& content )
{
    CORE::CFileAccess file( path, "rb" );
    if ( !file.Opened() )
        return false;
    const UInt64 size = file.GetSize();
    content.resize( (size_t) size );
    size_t done = 0;
    while ( done < content.size() )
    {
        const UInt32 chunk = (UInt32) ( content.size() - done > 16 * 1024 * 1024 ? 16 * 1024 * 1024 : content.size() - done );
        if ( file.Read( &content[ done ], 1, chunk ) != chunk )
            return false;
        done += chunk;
    }
    return true;
}

/*-------------------------------------------------------------------------*/

/** Writes the file next to where it is going and moves it into place, so a failed copy never leaves half a file */
static bool
WriteFileInPlace( const CORE::CString& path, const std::vector< char >& content )
{
    const CORE::CString temp = path + ".new";
    {
        CORE::CFileAccess file( temp, "wb" );
        if ( !file.Opened() )
            return false;
        size_t done = 0;
        while ( done < content.size() )
        {
            const UInt32 chunk = (UInt32) ( content.size() - done > 16 * 1024 * 1024 ? 16 * 1024 * 1024 : content.size() - done );
            if ( file.Write( &content[ done ], 1, chunk ) != chunk )
                return false;
            done += chunk;
        }
        file.Flush();
        file.Close();
    }
    return CORE::MoveFile( temp, path, true );
}

