int
CCommands::Discover( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    if ( !layout.CreateDiscoveryDirs() )
        return EXIT_CODE_USAGE;

    // earlier runs count too, the report is about everything that was recorded
    CEndpointCatalog catalog;
    catalog.SetRecordDna( settings.recordDna );
    const UInt32 earlier = CDiscoveryJournal::Load( layout, catalog );
    CDiscoveryJournal journal;
    if ( !journal.Open( layout ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to open the journal " + layout.GetDiscoveryJournalPath() );
        return EXIT_CODE_FAILED;
    }
    if ( earlier > 0 )
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Continuing the journal, it holds " + CORE::UInt32ToString( earlier ) + " requests already" );

    CChromeBrowser browser;
    ConfigureBrowser( settings, layout, browser );
    if ( !browser.EnsureRunning( settings.startUrl ) )
        return EXIT_CODE_BROWSER;

    WEB::CChromeDevToolsClient client;
    if ( !browser.ConnectToBrowser( client ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to connect to the browser" );
        return EXIT_CODE_BROWSER;
    }

    CChromeNetworkRecorder recorder( client, layout, catalog, journal );
    recorder.SetHostFilter( settings.hostFilter );
    recorder.SetMaxBodyBytes( settings.maxBodyBytes );
    if ( !recorder.Start() )
        return EXIT_CODE_BROWSER;

    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Recording requests to hosts containing: " + CORE::CString( settings.hostFilter.empty() ? "(everything)" : settings.hostFilter[ 0 ].c_str() ) );
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Now click through the site in the browser: open one well documented person and look at its facts, sources, media, comments, story and an attached record, and the media gallery of the tree." );
    if ( !settings.noWait && settings.discoverSeconds == 0 )
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Press Enter here when you are done." );

    CConsoleInput input;
    std::string line;
    const UInt64 start = NowInMs();
    UInt64 lastProgress = start;
    UInt32 lastReported = 0;
    bool browserGone = false;

    while ( !IsStopRequested() )
    {
        Pump( 10 );
        recorder.Process();

        std::string endpoint;
        while ( recorder.PopNewEndpoint( endpoint ) )
            GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: New endpoint: " + CORE::CString( endpoint.c_str() ) );

        if ( !client.IsConnected() )
        {
            GUCEF_WARNING_LOG( CORE::LOGLEVEL_NORMAL, "AncestryBackup: The browser was closed" );
            browserGone = true;
            break;
        }
        if ( !settings.noWait && settings.discoverSeconds == 0 && !input.IsInputClosed() && input.PollLine( line ) )
            break;
        if ( settings.discoverSeconds > 0 && NowInMs() - start >= (UInt64) settings.discoverSeconds * 1000 )
            break;
        if ( settings.noWait && settings.discoverSeconds == 0 )
            break;

        if ( NowInMs() - lastProgress >= 15000 && recorder.GetRecordedRequestCount() != lastReported )
        {
            lastProgress = NowInMs();
            lastReported = recorder.GetRecordedRequestCount();
            GUCEF_LOG( CORE::LOGLEVEL_NORMAL, "AncestryBackup: Recorded " + CORE::UInt32ToString( lastReported ) + " requests in " + CORE::UInt32ToString( (UInt32) catalog.GetEntries().size() ) + " endpoints" );
        }
    }

    // what was still loading
    for ( UInt32 i=0; i<20 && !browserGone; ++i )
    {
        Pump( 10 );
        recorder.Process();
    }
    recorder.Stop();
    journal.Close();

    if ( !CORE::WriteStringAsTextFile( layout.GetEndpointsReportPath(), catalog.RenderReport() ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + layout.GetEndpointsReportPath() );
        return EXIT_CODE_FAILED;
    }
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Recorded " + CORE::UInt32ToString( recorder.GetRecordedRequestCount() ) + " requests this run, " + CORE::UInt32ToString( recorder.GetSavedBodyCount() ) +
                                         " responses saved. The report is in " + layout.GetEndpointsReportPath() );
    return EXIT_CODE_OK;
}

