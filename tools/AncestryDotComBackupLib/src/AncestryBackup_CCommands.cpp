int
CCommands::Dna( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    if ( !layout.IsValid() )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The data directory or tree id is not valid" );
        return EXIT_CODE_USAGE;
    }

    // the id of the DNA test of the user: given, or seen when the DNA pages were studied
    std::string testId = settings.dnaSampleId.STL_String();
    if ( testId.empty() )
    {
        std::string journal;
        ReadAll( layout.GetDiscoveryJournalPath(), journal );
        testId = CDnaMatches::FindTestId( journal );
    }
    if ( testId.empty() )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The id of your DNA test is not known. Give dnaSampleId=<id>, it is the id that is in the address of the pages of your DNA matches" );
        return EXIT_CODE_USAGE;
    }
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Working with the DNA test " + CORE::CString( testId.c_str() ) );

    std::string siteTreeId, treeIdOrigin;
    if ( !ResolveSiteTreeId( settings, layout, siteTreeId, treeIdOrigin ) )
        siteTreeId = "0";       // not needed for DNA, the session wants a number

    const CORE::CString dnaDir = CORE::CombinePath( layout.GetTreeDir(), "dna" );
    const CORE::CString rawDir = CORE::CombinePath( dnaDir, "raw" );
    const CORE::CString matchesFile = CORE::CombinePath( dnaDir, "matches.jsonl" );
    const CORE::CString csvFile = CORE::CombinePath( dnaDir, "matches.csv" );
    const CORE::CString progressFile = CORE::CombinePath( dnaDir, "list-progress.txt" );
    const CORE::CString enrichedFile = CORE::CombinePath( dnaDir, "enriched-ids.txt" );
    CORE::CreateDirs( rawDir );

    CBrowserSession session( settings, layout, siteTreeId );
    session.GetPolicy().SetDnaAllowed( true );
    session.GetPolicy().AddDnaAllowed();
    session.SetPreferredTabUrlPart( "discoveryui-matches" );        // the requests are made from inside the DNA pages
    session.SetNeedsPostToken( true );
    if ( !session.Open() )
        return EXIT_CODE_BROWSER;

    std::vector< SDnaMatch > matches;
    LoadDnaMatches( matchesFile, matches );
    std::set< std::string > known;
    for ( size_t i=0; i<matches.size(); ++i )
        known.insert( matches[ i ].matchId );
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: " + CORE::UInt32ToString( (UInt32) matches.size() ) + " matches are here already" );

    // the list, 20 matches a page, goes on where an earlier run stopped
    std::string progress;
    ReadAll( progressFile, progress );
    UInt32 page = 1;
    bool listComplete = false;
    UInt32 totalPages = 0;
    if ( progress.find( "complete=1" ) != std::string::npos )
        listComplete = true;
    else
    if ( progress.compare( 0, 5, "page=" ) == 0 )
        page = (UInt32) strtoul( progress.c_str() + 5, GUCEF_NULL, 10 ) + 1;

    // which matches have their details already
    std::string doneText;
    ReadAll( enrichedFile, doneText );
    std::set< std::string > done;
    {
        size_t pos = 0;
        while ( pos < doneText.size() )
        {
            size_t end = doneText.find( '\n', pos );
            if ( end == std::string::npos )
                end = doneText.size();
            if ( end > pos )
                done.insert( doneText.substr( pos, end - pos ) );
            pos = end + 1;
        }
    }
    UInt32 enriched = 0;
    bool budgetEnded = false;
    while ( !listComplete )
    {
        SFetchResult response;
        if ( !session.GetText( CDnaMatches::BuildListUrl( testId, page ), true, response ) )
        {
            if ( response.error.compare( 0, 9, "no more r" ) == 0 )
            {
                GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Stopping for this run: " + CORE::CString( response.error.c_str() ) );
                budgetEnded = true;
                break;
            }
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Could not read the list of DNA matches: " + CORE::CString( response.error.c_str() ) );
            return response.halted ? EXIT_CODE_HALTED : EXIT_CODE_FAILED;
        }
        CORE::CDataNode document;
        SDnaMatchPage listed;
        if ( !COM::CJsonRpcEndpoint::ParseJsonText( CORE::CString( response.body.c_str() ), document ) || !CDnaMatches::ParseListPage( document, testId, listed ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The list of DNA matches did not answer in the form that is known" );
            return EXIT_CODE_FAILED;
        }
        if ( listed.totalPages > 0 )
            totalPages = listed.totalPages;
        CORE::WriteStringAsTextFile( CORE::CombinePath( rawDir, "list-" + CORE::UInt32ToString( page ) + ".json" ), CORE::CString( response.body.c_str() ) );

        // the details of this page's matches too, so that a match is complete as soon as it is in
        std::vector< SDnaMatch > group;
        for ( size_t i=0; i<listed.matches.size(); ++i )
            if ( done.find( listed.matches[ i ].matchId ) == done.end() )
                group.push_back( listed.matches[ i ] );
        if ( !group.empty() )
        {
            const EEnrichResult enrichResult = EnrichMatches( session, testId, rawDir, group );
            if ( enrichResult == ENRICH_BUDGET )
            {
                budgetEnded = true;
                break;
            }
            if ( enrichResult != ENRICH_OK )
                return enrichResult == ENRICH_HALTED ? EXIT_CODE_HALTED : EXIT_CODE_FAILED;
        }

        std::string lines, doneLines;
        for ( size_t i=0; i<group.size(); ++i )
        {
            lines += CDnaMatches::ToJsonLine( group[ i ] ) + "\n";
            doneLines += group[ i ].matchId + "\n";
            done.insert( group[ i ].matchId );
            if ( known.insert( group[ i ].matchId ).second )
                matches.push_back( group[ i ] );
            else
                for ( size_t m=0; m<matches.size(); ++m )
                    if ( matches[ m ].matchId == group[ i ].matchId )
                        matches[ m ] = group[ i ];
        }
        if ( !lines.empty() && ( !AppendTo( matchesFile, lines ) || !AppendTo( enrichedFile, doneLines ) ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + matchesFile );
            return EXIT_CODE_FAILED;
        }
        enriched += (UInt32) group.size();

        const bool last = listed.isLastPage || listed.matches.empty() || ( totalPages > 0 && page >= totalPages );
        CORE::WriteStringAsTextFile( progressFile, CORE::CString( ( last ? std::string( "complete=1\n" ) : "page=" + std::to_string( (unsigned long long) page ) + "\n" ).c_str() ) );
        if ( last )
            listComplete = true;
        else
            ++page;
    }

    // matches that came in without details earlier, such as from a run that was cut short
    for ( size_t first = 0; first < matches.size() && !budgetEnded; )
    {
        std::vector< size_t > batch;
        std::vector< std::string > ids;
        for ( ; first < matches.size() && batch.size() < 20; ++first )
            if ( done.find( matches[ first ].matchId ) == done.end() )
            {
                batch.push_back( first );
                ids.push_back( matches[ first ].matchId );
            }
        if ( batch.empty() )
            break;

        std::vector< SDnaMatch > group;
        for ( size_t i=0; i<batch.size(); ++i )
            group.push_back( matches[ batch[ i ] ] );

        const EEnrichResult enrichResult = EnrichMatches( session, testId, rawDir, group );
        if ( enrichResult == ENRICH_BUDGET )
        {
            budgetEnded = true;
            break;
        }
        if ( enrichResult != ENRICH_OK )
            return enrichResult == ENRICH_HALTED ? EXIT_CODE_HALTED : EXIT_CODE_FAILED;

        std::string lines, doneLines;
        for ( size_t i=0; i<group.size(); ++i )
        {
            matches[ batch[ i ] ] = group[ i ];
            lines += CDnaMatches::ToJsonLine( group[ i ] ) + "\n";
            doneLines += group[ i ].matchId + "\n";
            done.insert( group[ i ].matchId );
        }
        if ( !AppendTo( matchesFile, lines ) || !AppendTo( enrichedFile, doneLines ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + matchesFile );
            return EXIT_CODE_FAILED;
        }
        enriched += (UInt32) group.size();
    }

    if ( !WriteDnaCsv( csvFile, matches ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + csvFile );
        return EXIT_CODE_FAILED;
    }
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: DNA matches: " + CORE::UInt32ToString( (UInt32) matches.size() ) + " in the list" + ( listComplete ? "" : " so far (not all pages are read yet)" ) +
                                         ", " + CORE::UInt32ToString( (UInt32) done.size() ) + " with details (" + CORE::UInt32ToString( enriched ) + " now). The file is " + csvFile );
    return EXIT_CODE_OK;
}

