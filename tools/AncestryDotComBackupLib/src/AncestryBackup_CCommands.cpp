/** The details of up to 20 matches, asked for the way the site asks for them. The records in 'group' are completed. */
enum EEnrichResult { ENRICH_OK, ENRICH_BUDGET, ENRICH_HALTED, ENRICH_FAILED };

static EEnrichResult
EnrichMatches( CBrowserSession& session, const std::string& testId, const CORE::CString& rawDir, std::vector< SDnaMatch >& group )
{
    std::vector< std::string > ids;
    for ( size_t i=0; i<group.size(); ++i )
        ids.push_back( group[ i ].matchId );
    const std::string body = CDnaMatches::BuildIdsBody( ids );
    const std::string urls[ 2 ] = { CDnaMatches::BuildRelationshipsUrl( testId ), CDnaMatches::BuildProfilesUrl( testId ) };

    for ( int u=0; u<2; ++u )
    {
        SFetchResult response;
        if ( !session.PostJson( urls[ u ], body, response ) )
        {
            if ( response.error.compare( 0, 9, "no more r" ) == 0 )
            {
                GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Stopping for this run: " + CORE::CString( response.error.c_str() ) );
                return ENRICH_BUDGET;
            }
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Could not read the details of DNA matches: " + CORE::CString( response.error.c_str() ) );
            return response.halted ? ENRICH_HALTED : ENRICH_FAILED;
        }
        CORE::CDataNode document;
        if ( !COM::CJsonRpcEndpoint::ParseJsonText( CORE::CString( response.body.c_str() ), document ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The details of DNA matches did not answer in the form that is known" );
            return ENRICH_FAILED;
        }
        CORE::WriteStringAsTextFile( CORE::CombinePath( rawDir, CORE::CString( u == 0 ? "relationships-" : "profiles-" ) + ids[ 0 ].c_str() + ".json" ), CORE::CString( response.body.c_str() ) );
        if ( u == 0 )
            CDnaMatches::MergeRelationships( document, group );
        else
            CDnaMatches::MergeProfiles( document, group );
    }
    return ENRICH_OK;
}

