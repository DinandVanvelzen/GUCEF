int
CCommands::Report( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    CEndpointCatalog catalog;
    const UInt32 loaded = CDiscoveryJournal::Load( layout, catalog );
    if ( 0 == loaded )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: There are no recorded requests in " + layout.GetDiscoveryJournalPath() + ", run the discover command first" );
        return EXIT_CODE_FAILED;
    }

    if ( !CORE::CreateDirs( layout.GetDiscoveryDir() ) || !CORE::WriteStringAsTextFile( layout.GetEndpointsReportPath(), catalog.RenderReport() ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + layout.GetEndpointsReportPath() );
        return EXIT_CODE_FAILED;
    }
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Wrote the report of " + CORE::UInt32ToString( loaded ) + " requests to " + layout.GetEndpointsReportPath() );
    return EXIT_CODE_OK;
}

