/** The matches file keeps the latest line of each match */
static void
LoadDnaMatches( const CORE::CString& file, std::vector< SDnaMatch >& matches )
{
    std::string content;
    ReadAll( file, content );
    std::map< std::string, size_t > index;
    size_t start = 0;
    while ( start < content.size() )
    {
        size_t end = content.find( '\n', start );
        if ( end == std::string::npos )
            end = content.size();
        const std::string line = content.substr( start, end - start );
        start = end + 1;
        if ( line.empty() )
            continue;
        CORE::CDataNode document;
        SDnaMatch match;
        if ( !COM::CJsonRpcEndpoint::ParseJsonText( CORE::CString( line.c_str() ), document ) || !CDnaMatches::FromJsonLine( document, match ) )
            continue;
        std::map< std::string, size_t >::iterator found = index.find( match.matchId );
        if ( found == index.end() )
        {
            index[ match.matchId ] = matches.size();
            matches.push_back( match );
        }
        else
            matches[ found->second ] = match;
    }
}

/*-------------------------------------------------------------------------*/

static bool
WriteDnaCsv( const CORE::CString& file, std::vector< SDnaMatch >& matches )
{
    // closest first
    for ( size_t i=1; i<matches.size(); ++i )
        for ( size_t j=i; j>0 && matches[ j ].sharedCm > matches[ j - 1 ].sharedCm; --j )
            std::swap( matches[ j ], matches[ j - 1 ] );
    std::string csv = CDnaMatches::CsvHeader() + "\n";
    for ( size_t i=0; i<matches.size(); ++i )
        csv += CDnaMatches::ToCsvRow( matches[ i ] ) + "\n";
    return CORE::WriteStringAsTextFile( file, CORE::CString( csv.c_str() ) );
}

