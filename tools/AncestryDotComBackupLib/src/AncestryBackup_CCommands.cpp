int
CCommands::Export( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    if ( !layout.IsValid() )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The data directory or tree id is not valid" );
        return EXIT_CODE_USAGE;
    }

    std::vector< CORE::CString > dirs;
    for ( size_t i=0; i<settings.exportDirs.size(); ++i )
        dirs.push_back( CORE::RelativePath( settings.exportDirs[ i ].c_str() ) );
    if ( dirs.empty() )
        dirs = CExportFinder::GetDefaultDirs();
    if ( dirs.empty() )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: There is no downloads directory to look in, set exportDirs" );
        return EXIT_CODE_USAGE;
    }

    const UInt64 now = CORE::CDateTime::NowUTCDateTime().ToUnixEpochBasedTicksInMillisecs();
    const UInt64 maxAge = (UInt64) settings.exportMaxAgeDays * 24ULL * 60ULL * 60ULL * 1000ULL;
    std::vector< SExportCandidate > candidates;
    std::vector< CORE::CString > zips;
    CExportFinder::FindRecent( dirs, now, maxAge, candidates, &zips );

    // a zip with the export in it, the way the site delivers it
    std::vector< CORE::CString > recentZips;
    CExportFinder::FindRecentZips( dirs, now, maxAge, recentZips );
    if ( !recentZips.empty() && CZipExtractor::IsAvailable() )
    {
        const CORE::CString zipPath = recentZips[ 0 ];
        const UInt64 zipModified = CORE::GetFileModificationTime( zipPath ).ToUnixEpochBasedTicksInMillisecs();
        const CORE::CString zipSnapshot = CORE::CombinePath( layout.GetBaselineSnapshotsDir(), "export-" + CExportFinder::FormatTimestamp( zipModified ) + ".ged" );
        if ( ( candidates.empty() || candidates[ 0 ].modifiedAtInMs < zipModified ) )
        {
            if ( CORE::FileExists( zipSnapshot ) )
            {
                GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: The newest export, " + zipPath + ", was taken in already as " + zipSnapshot );
                return EXIT_CODE_OK;
            }
            GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Taking in " + zipPath );
            return ImportZip( layout, zipPath, zipModified );
        }
    }

    if ( candidates.empty() )
    {
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: There is no GEDCOM export of Ancestry from the last " + CORE::UInt32ToString( settings.exportMaxAgeDays ) + " days in " + dirs[ 0 ] +
                                             ( dirs.size() > 1 ? " and the other directories" : "" ) + ". Export the tree on the site (Tree Settings, Export tree) and download it." );
        for ( size_t i=0; i<zips.size(); ++i )
        {
            GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: " + zips[ i ] + " may hold an export but the archive plugin is not loaded, so zip files cannot be opened" );
        }
        return EXIT_CODE_NO_RECENT_EXPORT;
    }

    // the newest one, unless that one was taken in already
    const SExportCandidate& newest = candidates[ 0 ];
    const CORE::CString snapshot = CORE::CombinePath( layout.GetBaselineSnapshotsDir(), "export-" + CExportFinder::FormatTimestamp( newest.modifiedAtInMs ) + ".ged" );
    if ( CORE::FileExists( snapshot ) && CORE::FileSize( snapshot ) == newest.sizeInBytes )
    {
        GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: The newest export, " + newest.path + ", was taken in already as " + snapshot );
        return EXIT_CODE_OK;
    }

    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Taking in " + newest.path );
    return ImportGedcom( layout, newest.path, true, newest.modifiedAtInMs );
}

/*-------------------------------------------------------------------------*/

/** The id the site uses for the tree: asked for, else the tree id if it is a number, else what the baseline export says */
static bool
ResolveSiteTreeId( const CSettings& settings, const CDataLayout& layout, std::string& siteTreeId, std::string& origin )
{
    if ( !settings.siteTreeId.IsNULLOrEmpty() )
    {
        siteTreeId = settings.siteTreeId.STL_String();
        origin = "siteTreeId";
        return true;
    }
    const std::string name = layout.GetTreeId().STL_String();
    if ( !name.empty() && name.find_first_not_of( "0123456789" ) == std::string::npos )
    {
        siteTreeId = name;
        origin = "treeId";
        return true;
    }
    CORE::CFileAccess file( layout.GetBaselineGedcomPath(), "rb" );
    if ( file.Opened() )
    {
        std::vector< char > head( 16 * 1024 );
        const UInt32 got = file.Read( &head[ 0 ], 1, (UInt32) head.size() );
        CGedcomSummarizer summarizer;
        CGedcomReader::Parse( &head[ 0 ], got, summarizer );
        const std::string id = summarizer.GetSummary().treeId;
        if ( !id.empty() && id.find_first_not_of( "0123456789" ) == std::string::npos )
        {
            siteTreeId = id;
            origin = "the baseline export";
            return true;
        }
    }
    return false;
}

/*-------------------------------------------------------------------------*/

static bool
ReadAll( const CORE::CString& path, std::string& content )
{
    content.clear();
    if ( !CORE::FileExists( path ) )
        return true;
    CORE::CFileAccess file( path, "rb" );
    if ( !file.Opened() )
        return false;
    content.resize( (size_t) file.GetSize() );
    return content.empty() || file.Read( &content[ 0 ], 1, (UInt32) content.size() ) == content.size();
}

/*-------------------------------------------------------------------------*/

/** Appends to a file, creating it if needed */
static bool
AppendTo( const CORE::CString& path, const std::string& text )
{
    CORE::CFileAccess file( path, "ab" );
    if ( !file.Opened() )
        return false;
    const bool ok = file.Write( text.data(), 1, (UInt32) text.size() ) == text.size();
    file.Close();
    return ok;
}

/*-------------------------------------------------------------------------*/

/** When the baseline export was made, from its header */
static bool
BaselineTime( const CDataLayout& layout, UInt64& timeInMs )
{
    CORE::CFileAccess file( layout.GetBaselineGedcomPath(), "rb" );
    if ( !file.Opened() )
        return false;
    std::vector< char > head( 16 * 1024 );
    const UInt32 got = file.Read( &head[ 0 ], 1, (UInt32) head.size() );
    CGedcomSummarizer summarizer;
    CGedcomReader::Parse( &head[ 0 ], got, summarizer );
    return CChangeFeed::ParseGedcomDateTime( summarizer.GetSummary().headerDate, summarizer.GetSummary().headerTime, timeInMs );
}

