void
CCommands::Pump( UInt32 delayInMs )
{GUCEF_TRACE;

    CORE::CCoreGlobal::Instance()->GetPulseGenerator()->ForceDirectPulse();
    MT::ThreadDelay( delayInMs );
}

/*-------------------------------------------------------------------------*/

static UInt64
NowInMs( void )
{
    return (UInt64) ( MT::PrecisionTickCount() / ( MT::PrecisionTimerResolution() / 1000.0 ) );
}

/*-------------------------------------------------------------------------*/

static bool
EndsWithNoCase( const std::string& text, const std::string& suffix )
{
    if ( text.size() < suffix.size() )
        return false;
    for ( size_t i=0; i<suffix.size(); ++i )
        if ( tolower( text[ text.size() - suffix.size() + i ] ) != tolower( suffix[ i ] ) )
            return false;
    return true;
}

/*-------------------------------------------------------------------------*/

static void
ConfigureBrowser( const CSettings& settings, const CDataLayout& layout, CChromeBrowser& browser )
{
    browser.SetExecutablePath( settings.chromePath );
    browser.SetDebugPort( settings.debugPort );
    browser.SetProfileDir( layout.GetBrowserProfileDir() );
    browser.SetHeadless( settings.headless );
    browser.SetAttachToRunning( settings.attachToRunning );
    std::vector< CORE::CString > dataDirs;
    for ( size_t i=0; i<settings.chromeUserDataDirs.size(); ++i )
        dataDirs.push_back( settings.chromeUserDataDirs[ i ].c_str() );
    browser.SetUserDataDirs( dataDirs );
    for ( size_t i=0; i<settings.chromeArgs.size(); ++i )
        browser.AddArgument( settings.chromeArgs[ i ].c_str() );
}

