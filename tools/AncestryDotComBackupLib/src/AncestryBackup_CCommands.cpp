/** What is in the inventory file: the first part of each line, enough to know what is to be fetched */
static void
LoadInventory( const CORE::CString& file, std::vector< SMediaItem >& items, std::set< std::string >& ids )
{
    std::string content;
    ReadAll( file, content );
    size_t start = 0;
    while ( start < content.size() )
    {
        size_t end = content.find( '\n', start );
        if ( end == std::string::npos )
            end = content.size();
        const std::string line = content.substr( start, end - start );
        start = end + 1;
        if ( line.empty() )
            continue;
        CORE::CDataNode document;
        if ( !COM::CJsonRpcEndpoint::ParseJsonText( CORE::CString( line.c_str() ), document ) )
            continue;
        SMediaItem item;
        item.id = document.GetAttributeValue( "id" ).AsString().STL_String();
        item.lookupId = document.GetAttributeValue( "lookupId" ).AsString().STL_String();
        item.namespaceId = document.GetAttributeValue( "namespace" ).AsString().STL_String();
        item.category = document.GetAttributeValue( "category" ).AsString().STL_String();
        item.title = document.GetAttributeValue( "title" ).AsString().STL_String();
        const std::string fileName = document.GetAttributeValue( "file" ).AsString().STL_String();
        const size_t dot = fileName.find_last_of( '.' );
        item.extension = dot == std::string::npos ? std::string() : fileName.substr( dot + 1 );
        if ( item.id.empty() || !ids.insert( item.id ).second )
            continue;
        const CORE::CDataNode* object = document.Find( "item" );
        if ( GUCEF_NULL != object )
        {
            item.siteUrl = object->GetAttributeValue( "url" ).AsString().STL_String();
            item.width = object->GetAttributeValue( "width" ).AsString().STL_String();
            item.height = object->GetAttributeValue( "height" ).AsString().STL_String();
            CORE::CString json;
            if ( COM::CJsonRpcEndpoint::ToJsonText( *object, json ) )
                item.json = json.STL_String();
        }
        items.push_back( item );
    }
}

