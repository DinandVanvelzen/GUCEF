int
CCommands::Changes( const CSettings& settings )
{GUCEF_TRACE;

    const CDataLayout layout = settings.GetLayout();
    if ( !layout.IsValid() )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The data directory or tree id is not valid" );
        return EXIT_CODE_USAGE;
    }
    const CORE::CString stateFile = CORE::CombinePath( layout.GetStateDir(), "changes-state.txt" );
    const CORE::CString journalFile = CORE::CombinePath( layout.GetStateDir(), "changes.jsonl" );
    const CORE::CString peopleFile = CORE::CombinePath( layout.GetStateDir(), "changed-people.txt" );

    // where to start: what was asked for, else where the last run got to, else the time of the baseline export
    UInt64 since = 0;
    const char* origin = "";
    std::string state;
    ReadAll( stateFile, state );
    if ( !settings.changesSince.IsNULLOrEmpty() )
    {
        if ( !CChangeFeed::ParseTime( settings.changesSince.STL_String(), since ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: changesSince has to look like 2026-10-16T21:27:48Z, got \"" + settings.changesSince + "\"" );
            return EXIT_CODE_USAGE;
        }
        origin = "as asked";
    }
    else
    if ( state.compare( 0, 9, "lastTime=" ) == 0 && CChangeFeed::ParseTime( state.substr( 9, state.find_first_of( "\r\n" ) - 9 ), since ) )
        origin = "the last run";
    else
    if ( BaselineTime( layout, since ) )
        origin = "the baseline export";
    else
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: There is nothing to compare with: no earlier run, no baseline export (run the export command first) and no changesSince" );
        return EXIT_CODE_USAGE;
    }
    // exports and the feed do not agree to the second on when something happened, so a little of the past is looked at twice
    const UInt64 overlapInMs = 10ULL * 60ULL * 1000ULL;
    const UInt64 lookFrom = since > overlapInMs ? since - overlapInMs : 0;
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Looking for changes since " + CORE::CString( CChangeFeed::FormatTime( since ).c_str() ) + " (" + origin + ")" );

    std::string siteTreeId, treeIdOrigin;
    if ( !ResolveSiteTreeId( settings, layout, siteTreeId, treeIdOrigin ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The id Ancestry uses for the tree is not known: it is not the treeId, there is no baseline export that names it and siteTreeId was not given" );
        return EXIT_CODE_USAGE;
    }
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Working with tree " + CORE::CString( siteTreeId.c_str() ) + " (from " + CORE::CString( treeIdOrigin.c_str() ) + ")" );

    CBrowserSession session( settings, layout, siteTreeId );
    if ( !session.Open() )
        return EXIT_CODE_BROWSER;

    std::string known;
    ReadAll( journalFile, known );
    std::vector< SChangeEvent > fresh;
    std::string cursor;
    UInt32 pages = 0;
    bool reachedOlder = false;
    UInt64 newest = 0;

    while ( !reachedOlder && pages < settings.changesMaxPages )
    {
        SFetchResult response;
        if ( !session.GetText( CChangeFeed::BuildUrl( siteTreeId, 20, cursor ), true, response ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Could not read the change feed: " + CORE::CString( response.error.c_str() ) );
            return response.halted ? EXIT_CODE_HALTED : EXIT_CODE_FAILED;
        }
        ++pages;

        CORE::CDataNode document;
        SChangePage page;
        if ( !COM::CJsonRpcEndpoint::ParseJsonText( CORE::CString( response.body.c_str() ), document ) || !CChangeFeed::ParsePage( document, page ) )
        {
            GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: The change feed did not answer in the form that is known" );
            return EXIT_CODE_FAILED;
        }

        // the page as it was, for later
        const CORE::CString rawDir = CORE::CombinePath( layout.GetRawDir(), "changes" );
        CORE::CreateDirs( rawDir );
        CORE::WriteStringAsTextFile( CORE::CombinePath( rawDir, CExportFinder::FormatTimestamp( CORE::CDateTime::NowUTCDateTime().ToUnixEpochBasedTicksInMillisecs() ) + "-" + CORE::UInt32ToString( pages ) + ".json" ), CORE::CString( response.body.c_str() ) );

        for ( size_t i=0; i<page.events.size(); ++i )
        {
            const SChangeEvent& event = page.events[ i ];
            if ( event.timeInMs > newest )
                newest = event.timeInMs;
            if ( event.timeInMs < lookFrom )
            {
                reachedOlder = true;
                continue;
            }
            const std::string key = "\"referenceId\":\"" + event.referenceId + "\",\"author\"";
            if ( known.find( "\"time\":\"" + event.time + "\"" ) != std::string::npos && known.find( key ) != std::string::npos )
                continue;       // seen before
            fresh.push_back( event );
        }
        if ( page.events.empty() || page.nextCursor.empty() )
            break;
        cursor = page.nextCursor;
    }

    if ( !reachedOlder && pages >= settings.changesMaxPages )
        GUCEF_WARNING_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: Stopped after " + CORE::UInt32ToString( pages ) + " pages and did not reach the time asked for, there are older changes. Run again with more changesMaxPages, or this is where the next run goes on from." );

    // write down what was found. Newest first in the feed, oldest first in the journal
    std::string lines;
    std::map< std::string, UInt32 > perAction;
    for ( size_t i=fresh.size(); i>0; --i )
    {
        lines += CChangeFeed::ToJournalLine( fresh[ i - 1 ] ) + "\n";
        ++perAction[ fresh[ i - 1 ].action ];
    }
    if ( !lines.empty() && ( !CORE::CreateDirs( layout.GetStateDir() ) || !AppendTo( journalFile, lines ) ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + journalFile );
        return EXIT_CODE_FAILED;
    }

    // the people who need another look: the new ones and the ones that were still waiting for it
    std::string waiting;
    ReadAll( peopleFile, waiting );
    std::set< std::string > have;
    size_t pos = 0;
    while ( pos < waiting.size() )
    {
        size_t end = waiting.find_first_of( "\r\n", pos );
        if ( end == std::string::npos )
            end = waiting.size();
        if ( end > pos )
            have.insert( waiting.substr( pos, end - pos ) );
        pos = end + 1;
    }
    std::string addedPeople;
    UInt32 newPeople = 0;
    const std::vector< std::string > changed = CChangeFeed::GetChangedPeople( fresh );
    for ( size_t i=0; i<changed.size(); ++i )
        if ( have.insert( changed[ i ] ).second )
        {
            addedPeople += changed[ i ] + "\n";
            ++newPeople;
        }
    if ( !addedPeople.empty() && !AppendTo( peopleFile, addedPeople ) )
    {
        GUCEF_ERROR_LOG( CORE::LOGLEVEL_CRITICAL, "AncestryBackup: Unable to write " + peopleFile );
        return EXIT_CODE_FAILED;
    }

    // the next run starts where this one saw the newest change
    if ( newest > 0 && reachedOlder )
        CORE::WriteStringAsTextFile( stateFile, CORE::CString( ( "lastTime=" + CChangeFeed::FormatTime( newest ) + "\n" ).c_str() ) );
    else
    if ( newest > 0 && fresh.empty() )
        CORE::WriteStringAsTextFile( stateFile, CORE::CString( ( "lastTime=" + CChangeFeed::FormatTime( newest ) + "\n" ).c_str() ) );

    std::string summary;
    for ( std::map< std::string, UInt32 >::const_iterator a = perAction.begin(); a != perAction.end(); ++a )
        summary += ( summary.empty() ? "" : ", " ) + a->first + ": " + std::to_string( (unsigned long long) a->second );
    GUCEF_LOG( CORE::LOGLEVEL_IMPORTANT, "AncestryBackup: " + CORE::UInt32ToString( (UInt32) fresh.size() ) + " new changes in " + CORE::UInt32ToString( pages ) + " requests" +
                                         ( summary.empty() ? "" : " (" + CORE::CString( summary.c_str() ) + ")" ) + ", " + CORE::UInt32ToString( newPeople ) + " people to look at again, " +
                                         CORE::UInt32ToString( (UInt32) have.size() ) + " waiting in total. See " + peopleFile );
    return EXIT_CODE_OK;
}

