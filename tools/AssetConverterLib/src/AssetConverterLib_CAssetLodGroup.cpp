CAssetLodGroup::CAssetLodGroup( void )
    : name()
    , levels()
{GUCEF_TRACE;

}

/*-------------------------------------------------------------------------*/

void
CAssetLodGroup::AddLevel( UInt32 node, Float32 screenRelativeHeight )
{GUCEF_TRACE;

    SLevel level;
    level.node = node;
    level.screenRelativeHeight = screenRelativeHeight;
    levels.push_back( level );
}

