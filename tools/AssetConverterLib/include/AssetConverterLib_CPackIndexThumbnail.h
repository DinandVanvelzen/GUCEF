    UInt32 rendererVersion;
    CORE::CString path;
    bool automatic;                 /**< made by the automatic thumbnails of F2 */

    CPackIndexThumbnail( void );

    bool operator<( const CPackIndexThumbnail& other ) const;
    bool operator==( const CPackIndexThumbnail& other ) const;
    bool Serialize( CORE::CDataNode& node ) const;
