/**
 *  { kind, to, path, via?, optional? }: kind is usesMaterial, usesTexture, usesMesh, usesSkeleton, usesAnimation, instancesPrefab, inScene,
 *  fitsSkeleton, dependsOn or usesFile; to is the resource id of the target and path its path in the pack (the target need not be a resource
 *  of the document); via the original reference (a GUID, a res:// path, a uri); optional true when the resource is usable without the target
 */
class ASSETCONVERTERLIB_PUBLIC_CPP CPackIndexReference
{
    public:

    CORE::CString kind;
    CORE::CString to;
    CORE::CString via;
    CORE::CString path;
    bool optional;

    CPackIndexReference( void );

    /** The canonical order: by kind, then target, then the original reference, then the path */
    bool operator<( const CPackIndexReference& other ) const;
    bool Serialize( CORE::CDataNode& node ) const;
    bool Deserialize( const CORE::CDataNode& node );
};

