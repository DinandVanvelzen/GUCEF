/**
 *  What happened to an asset in a run: the action (imported, cached, failed, refused), the reason (new, unchanged,
 *  source changed, settings changed, version changed, dependency changed, output missing, forced, licence) with the
 *  detail that names the plugin, dependency or file, and the duration.
 */
class ASSETCONVERTERLIB_PUBLIC_CPP CImportActivityEntry
{
    public:

    CORE::CString assetPath;
    TActivityAction action;
    TActivityReason reason;
    CORE::CString detail;
    UInt32 durationInMs;

    CImportActivityEntry( void );

    bool Serialize( CORE::CDataNode& node ) const;
    bool Deserialize( const CORE::CDataNode& node );
};

