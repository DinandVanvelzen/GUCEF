/**
 *  A light of KHR_lights_punctual. It points along the forward axis of the coordinate system of the scene from the
 *  node that holds it; after the normalisation that is -Z, the glTF convention. Cone angles in radians, the range 0
 *  for no range. A value type.
 */
class ASSETCONVERTERLIB_PUBLIC_CPP CAssetLight
{
    public:

    CORE::CString name;
    TLightType type;
    Float32 colour[ 3 ];
    Float32 intensity;
    Float32 range;
    Float32 innerConeAngle;
    Float32 outerConeAngle;

    CAssetLight( void );

    bool Serialize( CORE::CDataNode& node ) const;
};

